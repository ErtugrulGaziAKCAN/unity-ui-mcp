        [Test]
        public void Sample_MatchesSnapshot()
        {
            var s = Sample();
            Assert.AreEqual("SampleScreen", s.ClassName);
            var uxml = UxmlWriter.Write(s, "SampleScreen.uss");
            var uss = UssWriter.Write(s);
            Dump("Sample.uxml", uxml);
            Dump("Sample.uss", uss);
            AssertSnapshot("Sample.uxml", uxml);
            AssertSnapshot("Sample.uss", uss);
        }

