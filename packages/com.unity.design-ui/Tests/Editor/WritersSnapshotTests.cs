            Assert.AreEqual("url(\"assets/pic.png\")", Decl(rule, "background-image"));
            Assert.AreEqual("1", Decl(rule, "flex-grow"));
        }

        // ---- wrapper removal -------------------------------------------------------------------------------

        static IrNode Block(string id, params IrNode[] kids) => new IrNode { Id = id, Kind = "container" }.Add(kids);

        [Test]
        public void Wrapper_WithoutEffect_IsRemoved()
        {
            var root = Block("root", Block("root__0", Text("t", "T", ("color", "#ffffff"))));
            var s = Build(Screen(root));
            CollectionAssert.AreEqual(new[] { "root__0" }, s.RemovedElements.ToArray());
            Assert.IsNull(s.Find("root__0"));
            Assert.AreSame(s.Find("t"), s.Root.Children.Single());
        }

        [Test]
        public void Wrapper_WithANamedIdOrStylesOrRowParent_IsKept()
        {
            var named = Build(Screen(Block("root", Block("panel", Text("t", "T")))));
            Assert.IsNotNull(named.Find("panel"), "data-u-id elements stay");
            var styled = Build(Screen(Block("root", Node("root__0", "container", ("padding-top", "4px")).Add(Text("t", "T")))));
            Assert.IsNotNull(styled.Find("root__0"));
            var row = Build(Screen(Root().With("base", ("display", "flex"), ("flex-direction", "row")).Add(Block("root__0", Text("t", "T")))));
            Assert.IsNotNull(row.Find("root__0"), "in a row the wrapper is stretched across, its child is not");
            var percent = Build(Screen(Block("root", Block("root__0", Node("c", "container", ("height", "50%"))))));
            Assert.IsNotNull(percent.Find("root__0"), "percentages resolve against the wrapper");
            var absolute = Build(Screen(Block("root", Block("root__0", Node("c", "container", ("position", "absolute"))).With("base", ("position", "relative")))));
            Assert.IsNotNull(absolute.Find("root__0"));
            Assert.AreEqual(0, named.RemovedElements.Count + styled.RemovedElements.Count + row.RemovedElements.Count);
        }

