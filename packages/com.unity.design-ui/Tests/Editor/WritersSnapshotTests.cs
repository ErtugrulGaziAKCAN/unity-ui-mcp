        [Test]
        public void ColourChange_ChangesOneClassDefinitionAndOneUxmlLine()
        {
            var before = Sample();
            var ir = IrReader.Read(IrReaderTests.SamplePath());
            ir.Root.Children[0].Style["base"]["color"] = "#ff0000"; // title
            var after = Build(ir);

            var uxmlA = UxmlWriter.Write(before, "SampleScreen.uss").Split('\n');
            var uxmlB = UxmlWriter.Write(after, "SampleScreen.uss").Split('\n');
            Assert.AreEqual(uxmlA.Length, uxmlB.Length);
            var changed = Enumerable.Range(0, uxmlA.Length).Where(i => uxmlA[i] != uxmlB[i]).ToList();
            Assert.AreEqual(1, changed.Count, "one UXML line changes");
            StringAssert.Contains("name=\"title\"", uxmlB[changed[0]]);

            var blocksA = UssWriter.Write(before).Split(new[] { "\n\n" }, StringSplitOptions.None);
            var blocksB = UssWriter.Write(after).Split(new[] { "\n\n" }, StringSplitOptions.None);
            Assert.AreEqual(blocksA.Length, blocksB.Length);
            var changedBlocks = Enumerable.Range(0, blocksA.Length).Where(i => blocksA[i] != blocksB[i]).ToList();
            Assert.AreEqual(1, changedBlocks.Count, "one class definition changes");
            StringAssert.Contains("." + Cls(after, "title") + " {", blocksB[changedBlocks[0]]);
            StringAssert.Contains("color: #ff0000;", blocksB[changedBlocks[0]]);
        }

        // ---- selector policy (spec 8) ----------------------------------------------------------------------

        [Test]
        public void Selectors_RootLayersAreCompound_DescendantLayersUseTheRootClass()
        {
            var s = Build(Showcase());
            var root = Cls(s, "root");
            Assert.AreEqual("0.5", Decl(Rule(s, "." + root + ".state-loading"), "opacity"));
            Assert.AreEqual("0.9", Decl(Rule(s, "." + root + ".bp-narrow"), "opacity"));
            var panel = Cls(s, "panel");
            Assert.AreEqual("#111111", Decl(Rule(s, "." + panel), "background-color"));
            Assert.AreEqual("#222222", Decl(Rule(s, ".state-loading ." + panel), "background-color"));
            Assert.AreEqual("#333333", Decl(Rule(s, "." + panel + ":hover"), "background-color"));
            Assert.AreEqual("#555555", Decl(Rule(s, "." + Cls(s, "go") + ":active"), "background-color"));

            // one class per selector, optionally one root state/breakpoint class before it and one pseudo-class or toggled class after it
            var policy = new Regex(@"^(\.(state|bp)-[a-z0-9_-]+ )?\.s-[0-9a-f]{8}((\.(state|bp)-[a-z0-9_-]+)|(:(hover|active|focus|checked|disabled))|(\.[A-Za-z_-][A-Za-z0-9_-]*))?$");
            foreach (var r in s.Rules) StringAssert.IsMatch(policy.ToString(), r.Selector);
        }

