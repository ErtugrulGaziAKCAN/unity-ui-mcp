        [Test]
        public void ImageWithGradient_GetsAContentChildAboveTheBackground()
        {
            var img = Node("pic", "image", ("width", "40px"), ("height", "40px"));
            img.Asset = new IrAsset { Kind = "image", File = "assets/pic.png", Sha256 = new string('e', 64), Width = 40, Height = 40 };
