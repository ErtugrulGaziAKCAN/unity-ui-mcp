        [Test]
        public void Selectors_RootLayersAreCompound_DescendantLayersUseTheRootClass()
        {
            var s = Build(Showcase());
            var root = Cls(s, "root");
            Assert.AreEqual("0.5", Decl(Rule(s, "." + root + ".state-loading"), "opacity"));
            Assert.AreEqual("0.9", Decl(Rule(s, "." + root + ".bp-narrow"), "opacity"));
            var panel = Cls(s, "panel");
