        static string ExpectedPath(string file) => IrReaderTests.PackagePath("Tests", "Editor", "Data", "expected~", file);

        static CompiledScreen Sample() => ScreenBuilder.Build(IrReader.Read(IrReaderTests.SamplePath()), RelativeAsset, null);

        static CompiledScreen Build(IrScreen ir, IReadOnlyDictionary<string, double> styles = null) =>
            ScreenBuilder.Build(ir, RelativeAsset, null, styles);

        static string Cls(CompiledScreen s, string name)
        {
            var e = s.Find(name);
            Assert.IsNotNull(e, "element " + name);
            return e.Classes.Single(c => c.StartsWith("s-", StringComparison.Ordinal));
        }

        static UssRule Rule(CompiledScreen s, string selector)
        {
            var rules = s.Rules.Where(r => r.Selector == selector).ToList();
            Assert.AreEqual(1, rules.Count, "one rule '" + selector + "' in:\n" + UssWriter.Write(s));
            return rules[0];
        }

        static string Decl(UssRule r, string property) => r.Declarations.Single(d => d.Property == property).Value;

        /// <summary>Compares with a snapshot; on a mismatch the actual text is written next to the temp folder for review.</summary>
        static string Dump(string file, string actual)
        {
            var dump = Path.Combine(Path.GetTempPath(), "design-ui-actual-" + file);
            File.WriteAllText(dump, actual);
            return dump;
        }

        static void AssertSnapshot(string file, string actual)
        {
            var path = ExpectedPath(file);
            var dump = Dump(file, actual);
            Assert.IsTrue(File.Exists(path), "missing snapshot " + path + " (actual written to " + dump + ")");
            Assert.AreEqual(File.ReadAllText(path), actual, "snapshot " + file + " differs (actual written to " + dump + ")");
        }

