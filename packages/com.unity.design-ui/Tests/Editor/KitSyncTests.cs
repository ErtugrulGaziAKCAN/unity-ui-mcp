            Assert.IsTrue(File.Exists(kit + "/fonts/OFL.txt"));
            Assert.IsFalse(File.Exists(kit + "/fonts/Other-LICENSE.txt"), "another family's licence in the same folder is not copied");
        }

        [Test]
