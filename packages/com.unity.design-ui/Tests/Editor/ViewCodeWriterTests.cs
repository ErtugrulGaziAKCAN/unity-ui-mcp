using System.Collections.Generic;
using System.Text.RegularExpressions;
using NUnit.Framework;
using static DesignUi.Editor.Tests.TestIr;

namespace DesignUi.Editor.Tests
{
    public class ViewCodeWriterTests
    {
        const string Ns = "DesignUi.Generated";

        static readonly Dictionary<string, double> Kit = new Dictionary<string, double> { { "label", 16.515625 }, { "body", 23.125 }, { "title", 46.28125 } };

        static CompiledScreen Build(IrScreen ir) => ScreenBuilder.Build(ir, RelativeAsset, null, Kit);

        /// <summary>contracts/ir-sample.json: a title with an argument, a shadowed card, a button with a label and a list repeat.</summary>
        static string SampleCode() => ViewCodeWriter.Write(Build(IrReader.Read(IrReaderTests.SamplePath())), Ns, "SampleScreenView");

        [Test]
        public void Write_Sample_HasTypedElementProperties()
        {
            var code = SampleCode();
            StringAssert.Contains("namespace DesignUi.Generated\n", code);
            StringAssert.Contains("public sealed partial class SampleScreenView\n", code);
            StringAssert.Contains("public SampleScreenView(VisualElement root)\n", code);
            StringAssert.Contains("public VisualElement Root { get; }", code);
            StringAssert.Contains("public Label Title { get; }", code);
            StringAssert.Contains("public VisualElement Card { get; }", code);
            StringAssert.Contains("public Button Play { get; }", code);
            StringAssert.Contains("public Label PlayLabel { get; }", code);
            StringAssert.Contains("public ListView Rows { get; }", code);
            StringAssert.Contains("Play = Find<Button>(root, \"play\");", code, "elements are found by their names");
        }

        [Test]
        public void Write_Sample_HasTheStateEnumAndSetStateSwapsTheRootClass()
        {
            var code = SampleCode();
            StringAssert.Contains("public enum State { Default, Loading }", code);
            StringAssert.Contains("public void SetState(State state)", code);
            StringAssert.Contains("{ null, \"state-loading\" }", code, "the default state has no class");
            StringAssert.Contains("EnableInClassList(", code);
        }

        [Test]
        public void Write_Sample_ExposesNoGeneratedOrRepeatItemElements_AndNoStyleClasses()
        {
            var code = SampleCode();
            StringAssert.DoesNotContain("CardShadow", code, "compiler-made names (__shadowhost, __shadow) are not exposed");
            StringAssert.DoesNotContain(" Row ", code, "list item template elements belong to the item view");
            StringAssert.DoesNotContain("RowName", code);
            Assert.IsFalse(Regex.IsMatch(code, @"\bs-[0-9a-f]{8}\b"), "hashed style classes change with every style edit; the view never names them");
            StringAssert.DoesNotContain("\r", code);
            StringAssert.StartsWith("// <auto-generated>", code);
        }

        [Test]
        public void Write_IsDeterministic()
        {
            Assert.AreEqual(SampleCode(), SampleCode());
        }

        [Test]
        public void Write_Showcase_WiresClickablesAndPseudoStateMirrorsInTheConstructor()
        {
            var s = Build(Showcase());
            Assert.IsTrue(s.Find("tile").Clickable, "fixture: tile has an :active layer");
            Assert.AreEqual("card", s.Find("card__shadowhost").MirrorElement, "fixture: card's hover layer moved to its host");
            var code = ViewCodeWriter.Write(s, Ns, "TestShowcaseView");
            StringAssert.Contains("Tile.AddManipulator(new Clickable(", code);
            StringAssert.Contains("Card.AddManipulator(new global::DesignUi.PseudoStateMirror(Find<VisualElement>(root, \"card__shadowhost\")));", code);
            StringAssert.DoesNotContain("Go.AddManipulator(new Clickable(", code, "a Button has its own Clickable");
            StringAssert.DoesNotContain("ItemA", code, "inline repeat items belong to the item view");
        }

        [Test]
        public void Write_TwoIdsWithTheSameMemberName_Throws()
        {
            var ir = TestIr.Screen(Root(Node("card-title", "container"), Node("card.title", "container")));
            var e = Assert.Throws<IrFormatException>(() => ViewCodeWriter.Write(Build(ir), Ns, "TestScreenView"));
            StringAssert.Contains("card-title", e.Message);
            StringAssert.Contains("card.title", e.Message);
            StringAssert.Contains("CardTitle", e.Message);
        }

        [TestCase("state")]
        [TestCase("set-state")]
        [TestCase("test-screen-view")]
        [TestCase("to-string")]
        public void Write_IdThatGivesAReservedMemberName_Throws(string id)
        {
            var ir = TestIr.Screen(Root(Node(id, "container")));
            var e = Assert.Throws<IrFormatException>(() => ViewCodeWriter.Write(Build(ir), Ns, "TestScreenView"));
            StringAssert.Contains("'" + id + "'", e.Message);
        }

        [Test]
        public void Write_StatesThatGiveTheSameName_Throw()
        {
            var ir = TestIr.Screen(Root());
            ir.States = new[] { "default", "my-state", "my_state" };
            var e = Assert.Throws<IrFormatException>(() => ViewCodeWriter.Write(Build(ir), Ns, "TestScreenView"));
            StringAssert.Contains("my-state", e.Message);
        }

        [TestCase("My Game.Views")]
        [TestCase("Game..Views")]
        [TestCase("Game.class")]
        [TestCase("")]
        public void Write_InvalidNamespace_Throws(string ns)
        {
            Assert.Throws<IrFormatException>(() => ViewCodeWriter.Write(Build(TestIr.Screen(Root())), ns, "TestScreenView"));
        }
    }
}
