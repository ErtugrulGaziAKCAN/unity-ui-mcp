        /// <summary>contracts/ir-sample.json: a title with an argument, a shadowed card, a button with a label and a list repeat.</summary>
        static string SampleCode() => ViewCodeWriter.Write(Build(IrReader.Read(IrReaderTests.SamplePath())), Ns, "SampleScreenView");

        /// <summary>The text of the screen view class up to its first nested item view class.</summary>
        static string ScreenPart(string code)
        {
            var nested = code.IndexOf("        public sealed partial class ", System.StringComparison.Ordinal);
            return nested < 0 ? code : code.Substring(0, nested);
        }

        /// <summary>The text of a nested item view class.</summary>
        static string ItemPart(string code, string itemClass)
        {
            var start = code.IndexOf("public sealed partial class " + itemClass + " ", System.StringComparison.Ordinal);
            Assert.GreaterOrEqual(start, 0, "item view class " + itemClass);
            var end = code.IndexOf("\n        }\n", start, System.StringComparison.Ordinal);
            return code.Substring(start, end - start);
        }

