        // ---- repeats ----------------------------------------------------------------------------------------------------

        internal static IrScreen Repeats()
        {
            var cellValue = Text("cell-value", "7", ("font-size", "16.515625px"));
            cellValue.Bind = "cell.value";
            var cells = Node("cells", "container", ("display", "flex"), ("flex-direction", "row"), ("gap", "4px"))
                .Add(Node("cell", "container", ("width", "20px")).Add(cellValue));
            cells.Repeat = new IrRepeat { Name = "cell", Mode = "inline", Count = 3 };
            var rowName = Text("row-name", "Ahmet", ("font-size", "16.515625px"));
            rowName.Bind = "row.name";
            var row = Node("row", "container", ("height", "40px")).Add(rowName, cells);
            row.Action = "open-row";
            var rows = Node("rows", "list", ("display", "flex"), ("flex-direction", "column"), ("overflow-y", "auto"), ("height", "200px")).Add(row);
            rows.Repeat = new IrRepeat { Name = "row", Mode = "list", Count = 4 };
            var chip = Node("chip", "container", ("height", "10px"));
            chip.Action = "pick-chip";
            var chips = Node("chips", "container", ("display", "flex"), ("flex-direction", "column"), ("gap", "2px")).Add(chip);
            chips.Repeat = new IrRepeat { Name = "chip", Mode = "inline", Count = 2 };
            return TestIr.Screen(Root(chips, rows));
        }

        [Test]
        public void Write_Repeats_GiveSetItemsSetters_AndNestedItemViews()
        {
            var code = ViewCodeWriter.Write(Build(Repeats()), Ns, "TestScreenView");
            var screen = ScreenPart(code);
            StringAssert.Contains("public void SetChip(int count, Action<ChipItemView, int> bind) => m_Repeat0.SetItems(count, bind);", screen);
            StringAssert.Contains("m_Repeat0 = new global::DesignUi.DesignInlineRepeat<ChipItemView>(Chips, new[] { \"chip\" }, m_Context.Template(\"ChipItem\"), r => new ChipItemView(r, m_Context));", screen);
            StringAssert.Contains("public void SetRow(int count, Action<RowItemView, int> bind) => m_Repeat1.SetItems(count, bind);", screen);
            StringAssert.Contains("m_Repeat1 = new global::DesignUi.DesignListRepeat<RowItemView>(Rows, m_Context.Template(\"RowItem\"), r => new RowItemView(r, m_Context));", screen);
            StringAssert.DoesNotContain("SetCell(", screen, "the nested repeat belongs to the row's item view");
            StringAssert.DoesNotContain("OpenRowRequested", screen);

            var row = ItemPart(code, "RowItemView");
            StringAssert.Contains("public sealed partial class RowItemView : global::DesignUi.IDesignRepeatItem", row);
            StringAssert.Contains("internal RowItemView(VisualElement[] roots, global::DesignUi.DesignViewContext context)", row);
            StringAssert.Contains("public void SetRowName(string value)", row);
            StringAssert.Contains("public event Action OpenRowRequested;", row);
            StringAssert.Contains("public void SetCell(int count, Action<CellItemView, int> bind)", row, "a nested repeat: one level deeper");
            StringAssert.Contains("new global::DesignUi.DesignInlineRepeat<CellItemView>(Cells, new[] { \"cell\" }, m_Context.Template(\"CellItem\")", row);
            StringAssert.Contains("void global::DesignUi.IDesignRepeatItem.BeginBind(int index)", row);
            StringAssert.Contains("OpenRowRequested = null;", row, "the item's events are cleared before each bind");
            StringAssert.Contains("public int Index { get; private set; } = -1;", row);

            var cell = ItemPart(code, "CellItemView");
            StringAssert.Contains("public void SetCellValue(string value)", cell);
            StringAssert.DoesNotContain("m_Context;", ItemPart(code, "ChipItemView"), "an item view that needs no context keeps none (no unread field)");
        }

