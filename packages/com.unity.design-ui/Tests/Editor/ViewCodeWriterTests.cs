        [Test]
        public void Write_Sample_ExposesNoGeneratedOrRepeatItemElementsOnTheScreen_AndNoStyleClasses()
        {
            var code = SampleCode();
            var screen = ScreenPart(code);
            StringAssert.DoesNotContain("CardShadow", code, "compiler-made names (__shadowhost, __shadow) are not exposed");
            StringAssert.DoesNotContain(" Row ", screen, "list item template elements belong to the item view");
            StringAssert.DoesNotContain("RowName", screen);
            var item = ItemPart(code, "RowItemView");
