            StringAssert.Contains("public Label RowName { get; }", item);
            Assert.IsFalse(Regex.IsMatch(code, @"\bs-[0-9a-f]{8}\b"), "hashed style classes change with every style edit; the view never names them");
            StringAssert.DoesNotContain("\r", code);
            StringAssert.StartsWith("// <auto-generated by com.unity.design-ui>\n", code, "the package marker, which Roslyn also reads as generated code");
        }

