namespace DesignUi.Editor
{
    public sealed class KitSyncResult
    {
        public bool Ok => Errors.Count == 0;
        /// <summary>Kit files the sync owns, relative to the kit folder with '/' separators.</summary>
        public IReadOnlyList<string> Files = new string[0];
        /// <summary>The files of <see cref="Files"/> whose content changed and were written in this run.</summary>
        public IReadOnlyList<string> Written = new string[0];
        /// <summary>Asset paths of the locales' UI Toolkit font twins (created or updated as needed).</summary>
        public IReadOnlyList<string> Twins = new string[0];
        public IReadOnlyList<string> Warnings = new string[0];
        /// <summary>Why the sync stopped; nothing is written into the kit when there are errors.</summary>
        public IReadOnlyList<string> Errors = new string[0];
    }

    /// <summary>
    /// Font sync (spec 5.1, 6): the Unity project is the source of truth. For the profile's locales (reference first) it
    /// resolves the TMP fonts, creates or updates their UI Toolkit twins, checks the kit's text styles against the
    /// reference locale's twin (docs/findings/m0.md: line height and text styles, bold policy), and writes into the kit folder:
    /// <list type="bullet">
    /// <item><c>fonts/&lt;file&gt;</c>: the source TTF/OTF of every font TMP searches for a locale, with the licence files next to it;</item>
    /// <item><c>fonts/fonts.css</c>: one <c>@font-face</c> per family and weight (family = the TMP face's family name; weights from the TMP weight table);</item>
    /// <item><c>fonts/fonts.json</c>: locale → families, in TMP's search order;</item>
    /// <item><c>kit.config.json</c>: <c>reference</c>, <c>viewports</c>, <c>screenMatch</c> and <c>locales</c> from the profile; other keys are kept.</item>
    /// </list>
    /// The paths of <c>fonts.css</c> and the text styles come from <c>kit.config.json</c>. Files are written only when
    /// their content changes; files in the fonts folder that no locale uses are reported, not deleted.
    /// </summary>
    public static class KitSync
    {
        public const string ConfigFileName = "kit.config.json";

        /// <summary>A text style's UI Toolkit line pitch stays at least this far below its line height (docs/findings/m0.md, line height and text styles).</summary>
        public const double PitchMargin = 0.001;

        const string Marker = "/* auto-generated by com.unity.design-ui: the Unity project's TMP fonts per locale (kit sync) */";

        static readonly Regex LicenceName = new Regex(@"^(ofl|licen[cs]e|copying|notice)([._ -].*)?$", RegexOptions.Compiled | RegexOptions.IgnoreCase);

        public static KitSyncResult Run(DesignUiProfile profile, string kitDir, IFontResolver resolver)
        {
            var errors = new List<string>();
            var warnings = new List<string>();
            if (profile == null) return Failed(new[] { "no DesignUiProfile" }, warnings);
            resolver = resolver ?? FontMap.DefaultResolver(profile);
            if (string.IsNullOrEmpty(kitDir) || !Directory.Exists(kitDir)) return Failed(new[] { "the kit folder '" + kitDir + "' does not exist" }, warnings);
            kitDir = kitDir.Replace('\\', '/').TrimEnd('/');

            // ---- the kit's configuration -------------------------------------------------------------------------------
            byte[] configBytes;
            JObject config;
            try
            {
                configBytes = File.ReadAllBytes(kitDir + "/" + ConfigFileName);
                config = JObject.Parse(Encoding.UTF8.GetString(configBytes));
            }
            catch (Exception e) when (e is IOException || e is UnauthorizedAccessException || e is JsonException)
            {
                return Failed(new[] { "cannot read " + ConfigFileName + " in the kit folder '" + kitDir + "': " + e.Message }, warnings);
            }
            var fontsCss = KitRelative(config, "fontsCss", "fonts/fonts.css", errors);
            var textStyles = KitRelative(config, "textStyles", "text-styles.json", errors);
            if (profile.referenceResolution.x <= 0 || profile.referenceResolution.y <= 0) errors.Add("the DesignUiProfile's reference resolution must be positive");
            if (profile.viewports == null || profile.viewports.Length == 0 || profile.viewports.Any(v => v.x <= 0 || v.y <= 0))
                errors.Add("the DesignUiProfile needs at least one viewport, each with a positive size");

            var settings = FindTmpSettingsAssets();
            if (settings.Count > 1) warnings.Add("Multiple TMP Settings assets under Resources: " + string.Join(", ", settings));

            // ---- fonts per locale (nothing is written before everything checks out) -------------------------------------
            var plan = FontMap.Plan(profile, resolver);
            errors.AddRange(plan.Errors);
            foreach (var locale in plan.Missing) errors.Add("Font not resolvable: " + FontMap.NoFont(locale));
            if (errors.Count > 0) return Failed(errors, warnings);

            var faces = Faces(plan, errors);
            foreach (var locale in plan.Locales)
            {
                var font = plan.Fonts[locale];
                var own = FontMap.Chain(new ResolvedFont { Primary = font.Primary });
                var globals = font.Fallbacks.Where(f => f != null && !own.Contains(f)).Select(f => f.name).ToList();
                if (globals.Count > 0)
                    warnings.Add("locale '" + locale + "': TMP searches the global fallback fonts " + string.Join(", ", globals.Select(n => "'" + n + "'")) +
                                 " after '" + font.Primary.name + "', but its UI Toolkit twin has only the font asset's own fallback list; add them there so both render the same glyphs");
            }
            if (errors.Count > 0) return Failed(errors, warnings);

            FontTwinGenerator.TwinRun twins;
            try { twins = FontMap.EnsureTwins(plan, profile.outputFolder); }
            catch (FontSetupException e) { return Failed(new[] { e.Message }, warnings); }
            var twinPaths = twins.Twins.Values.Select(AssetDatabase.GetAssetPath).Distinct().OrderBy(p => p, StringComparer.Ordinal).ToList();

            errors.AddRange(ValidateTextStyles(kitDir + "/" + textStyles, plan.Fonts[plan.ReferenceLocale].Primary, twins));
            if (errors.Count > 0) return Failed(errors, warnings, twinPaths);

            // ---- kit outputs ---------------------------------------------------------------------------------------------
            var fontsDir = Path.GetDirectoryName(fontsCss)?.Replace('\\', '/') ?? "";
            string InFonts(string name) => fontsDir.Length > 0 ? fontsDir + "/" + name : name;
            var outputs = new SortedDictionary<string, byte[]>(StringComparer.Ordinal);
            var copies = FontFiles(faces, errors);
            if (errors.Count > 0) return Failed(errors, warnings, twinPaths);
            foreach (var kv in copies) outputs[InFonts(kv.Key)] = kv.Value;
            var fontsJson = Regex.Replace(fontsCss, @"\.css$", "", RegexOptions.IgnoreCase) + ".json";
            outputs[fontsCss] = Utf8(FontsCss(faces));
            outputs[fontsJson] = Utf8(FontsJson(plan));
            outputs[ConfigFileName] = UpdatedConfig(config, configBytes, profile, plan);
            var text = new HashSet<string>(StringComparer.Ordinal) { fontsCss, fontsJson, ConfigFileName };

            var written = new List<string>();
            try
            {
                foreach (var kv in outputs)
                    if (WriteIfChanged(kitDir + "/" + kv.Key, kv.Value, text.Contains(kv.Key))) written.Add(kv.Key);
            }
            catch (Exception e) when (e is IOException || e is UnauthorizedAccessException)
            {
                return new KitSyncResult { Files = outputs.Keys.ToList(), Written = written, Twins = twinPaths, Warnings = warnings, Errors = new[] { "writing the kit failed: " + e.Message } };
            }

            var fontsAbs = fontsDir.Length > 0 ? kitDir + "/" + fontsDir : kitDir;
            if (fontsDir.Length > 0 && Directory.Exists(fontsAbs))
            {
                var unknown = Directory.GetFiles(fontsAbs).Select(Path.GetFileName)
                    .Where(n => !n.StartsWith(".", StringComparison.Ordinal) && !n.EndsWith(".meta", StringComparison.Ordinal) && !outputs.ContainsKey(InFonts(n)))
                    .OrderBy(n => n, StringComparer.Ordinal).ToList();
                if (unknown.Count > 0)
                    warnings.Add("the kit's " + fontsDir + "/ folder has files no locale font uses: " + string.Join(", ", unknown) + " (left in place; delete them if they are stale)");
            }
            return new KitSyncResult { Files = outputs.Keys.ToList(), Written = written, Twins = twinPaths, Warnings = warnings };
        }

        /// <summary>
        /// TMP Settings assets <c>Resources.Load("TMP Settings")</c> can reach (named "TMP Settings", directly in a
        /// Resources folder), sorted. More than one makes the settings TMP uses depend on load order.
        /// </summary>
        public static IReadOnlyList<string> FindTmpSettingsAssets() =>
            AssetDatabase.FindAssets("t:" + nameof(TMP_Settings))
                .Select(AssetDatabase.GUIDToAssetPath)
                .Where(p => Path.GetFileNameWithoutExtension(p) == "TMP Settings" && Path.GetFileName(Path.GetDirectoryName(p)) == "Resources")
                .Distinct()
                .OrderBy(p => p, StringComparer.Ordinal)
                .ToList();

        // ---- text styles (docs/findings/m0.md: line height and text styles, bold policy) ---------------------------

        /// <summary>
        /// Checks every kit text style against the reference locale's font: the weight has a real face (the TMP weight
        /// table, 400 = the font itself); the line height is a whole multiple of 4 px; the font size is a multiple of 1/64 px
        /// whose UI Toolkit line pitch <c>P = fontSize × faceInfo.lineHeight / faceInfo.pointSize</c> (of the face's twin)
        /// fills the line: <c>ceil(P) = lineHeight</c> and <c>lineHeight − P ≥ 0.001</c>. Errors name the computed fix, the
        /// largest such size.
        /// </summary>
        internal static List<string> ValidateTextStyles(string path, TMP_FontAsset reference, FontTwinGenerator.TwinRun twins)
        {
            var errors = new List<string>();
            JObject styles;
            try
            {
                using (var reader = new JsonTextReader(new StringReader(File.ReadAllText(path))) { FloatParseHandling = FloatParseHandling.Double })
                    styles = JObject.Load(reader);
            }
            catch (Exception e) when (e is IOException || e is UnauthorizedAccessException || e is JsonException)
            {
                errors.Add("cannot read the kit's text styles '" + path + "': " + e.Message);
                return errors;
            }

            foreach (var p in styles.Properties())
            {
                var style = p.Value as JObject;
                double? Num(string key)
                {
                    var t = style?[key];
                    return t != null && (t.Type == JTokenType.Integer || t.Type == JTokenType.Float) ? t.Value<double>() : (double?)null;
                }
                var size = Num("fontSize");
                var line = Num("lineHeight");
                var weight = Num("weight") ?? 400;
                var prefix = "text style '" + p.Name + "': ";
                if (size == null || line == null || size <= 0 || line <= 0)
                {
                    errors.Add(prefix + "needs a positive fontSize and lineHeight");
                    continue;
                }
                if (weight < 100 || weight > 900 || weight % 100 != 0)
                {
                    errors.Add(prefix + "weight " + Fmt(weight) + " is not one of 100, 200, … 900");
                    continue;
                }
                var w = (int)weight;
                var face = w == 400 ? reference : RealFace(reference, w);
                if (face == null)
                {
                    errors.Add(prefix + "uses weight " + w + ", but the reference locale's font '" + reference.name + "' has no real face for it: add that face to " +
                               "the TMP font asset's weight table (" + w + "). A synthesized weight renders with different advances in UI Toolkit and Chromium.");
                    continue;
                }
                if (!twins.Twins.TryGetValue(face, out var twin) || twin == null || twin.faceInfo.pointSize <= 0)
                {
                    errors.Add(prefix + "the UI Toolkit twin of '" + face.name + "' is missing");
                    continue;
                }
                var ratio = (double)twin.faceInfo.lineHeight / twin.faceInfo.pointSize;
                var pitchRule = "pitch = fontSize × " + Fmt(twin.faceInfo.lineHeight) + " / " + Fmt(twin.faceInfo.pointSize) + " for '" + face.name + "'";
                var l = line.Value;
                if (l != Math.Floor(l) || (long)l % 4 != 0)
                {
                    var nearest = Math.Max(4, Math.Round(l / 4, MidpointRounding.AwayFromZero) * 4);
                    errors.Add(prefix + "lineHeight " + Fmt(l) + " px is not a multiple of 4 px (a line must be whole device pixels at the 0.75 and 0.5 viewport scales); " +
                               "use lineHeight " + Fmt(nearest) + " with fontSize " + Fmt(LargestSize(nearest, ratio)));
                    continue;
                }
                var fix = LargestSize(l, ratio);
                var f = size.Value;
                var pitch = f * ratio;
                if (Math.Abs(f * 64 - Math.Round(f * 64)) > 1e-9)
                    errors.Add(prefix + "fontSize " + Fmt(f) + " px is not a multiple of 1/64 px; use fontSize " + Fmt(fix) +
                               " (the largest 1/64 px size whose UI Toolkit line pitch stays " + Fmt(PitchMargin) + " px below lineHeight " + Fmt(l) + "; " + pitchRule + ")");
                else if (l - pitch < PitchMargin - 1e-9)
                    errors.Add(prefix + "fontSize " + Fmt(f) + " px gives a UI Toolkit line pitch of " + pitch.ToString("0.#####", CultureInfo.InvariantCulture) + " px (" + pitchRule +
                               "), which is not " + Fmt(PitchMargin) + " px below lineHeight " + Fmt(l) + "; use fontSize " + Fmt(fix));
                else if (Math.Ceiling(pitch) != l)
                    errors.Add(prefix + "fontSize " + Fmt(f) + " px gives a UI Toolkit line pitch of " + pitch.ToString("0.#####", CultureInfo.InvariantCulture) + " px (" + pitchRule +
                               "), so one line is " + Fmt(Math.Ceiling(pitch)) + " px tall in UI Toolkit, not lineHeight " + Fmt(l) + "; use fontSize " + Fmt(fix));
            }
            return errors;
        }

        /// <summary>The largest multiple of 1/64 px whose pitch stays <see cref="PitchMargin"/> below the line height.</summary>
        internal static double LargestSize(double lineHeight, double ratio)
        {
            var f = Math.Floor((lineHeight - PitchMargin) / ratio * 64) / 64;
            while (f > 0 && lineHeight - f * ratio < PitchMargin) f -= 1.0 / 64;
            return f;
        }

        static TMP_FontAsset RealFace(TMP_FontAsset font, int weight)
        {
            var table = font.fontWeightTable;
            var i = weight / 100;
            return table != null && i < table.Length ? table[i].regularTypeface : null;
        }

        // ---- faces and files -----------------------------------------------------------------------------------------

        sealed class Face
        {
            public string Family;
            public int Weight;
            public bool Italic;
            public string Source;
            public string Owner;
            public string File;
        }

        /// <summary>
        /// The @font-face list: per locale (reference first) every font TMP searches, as its family at 400 plus the faces
        /// of its weight table. One family, weight and style is one file; two different files are an error.
        /// </summary>
        static List<Face> Faces(FontMap.FontsPlan plan, List<string> errors)
        {
            var faces = new List<Face>();
            void Add(string family, int weight, bool italic, TMP_FontAsset asset, bool fromTable)
            {
                string source;
                try { source = TmpSourceFont.GetSourceFontPath(asset); }
                catch (FontSetupException e)
                {
                    if (!errors.Contains(e.Message)) errors.Add(e.Message);
                    return;
                }
                var existing = faces.FirstOrDefault(x => x.Family == family && x.Weight == weight && x.Italic == italic);
                if (existing == null)
                {
                    faces.Add(new Face { Family = family, Weight = weight, Italic = italic, Source = source, Owner = asset.name });
                    return;
                }
                if (existing.Source == source || fromTable && weight == 400 && !italic) return; // the font itself is its own regular face
                errors.Add("font family '" + family + "' weight " + weight + (italic ? " italic" : "") + " would be two files in the kit: '" + existing.Source + "' ('" +
                           existing.Owner + "') and '" + source + "' ('" + asset.name + "'). Give the TMP font assets different family names, or use one source font.");
            }

            foreach (var locale in plan.Locales)
            {
                if (!plan.Chains.TryGetValue(locale, out var chain)) continue;
                foreach (var asset in chain)
                {
                    var family = asset.faceInfo.familyName;
                    if (string.IsNullOrWhiteSpace(family)) continue; // reported by the plan
                    Add(family, 400, false, asset, false);
                    var table = asset.fontWeightTable;
                    if (table == null) continue;
                    for (int i = 1; i < table.Length && i <= 9; i++)
                    {
                        if (table[i].regularTypeface != null) Add(family, i * 100, false, table[i].regularTypeface, true);
                        if (table[i].italicTypeface != null) Add(family, i * 100, true, table[i].italicTypeface, true);
                    }
                }
            }
            return faces;
        }

        /// <summary>
        /// Kit file name → bytes for the faces' source fonts and the licence files next to them. Names stay the source
        /// file names; a licence whose name is taken by a different file gets its folder name as a prefix.
        /// </summary>
        static SortedDictionary<string, byte[]> FontFiles(List<Face> faces, List<string> errors)
        {
            var files = new SortedDictionary<string, byte[]>(StringComparer.Ordinal);
            var origin = new Dictionary<string, string>(StringComparer.Ordinal);
            var folders = new List<string>();
            foreach (var face in faces)
            {
                var name = Path.GetFileName(face.Source);
                face.File = name;
                if (origin.TryGetValue(name, out var other) && other == face.Source) continue;
                var bytes = File.ReadAllBytes(Path.GetFullPath(face.Source));
                if (files.TryGetValue(name, out var taken) && !taken.SequenceEqual(bytes))
                {
                    errors.Add("two different font files are named '" + name + "' ('" + other + "' and '" + face.Source + "'); rename one of them");
                    continue;
                }
                files[name] = bytes;
                origin[name] = face.Source;
                var folder = Path.GetDirectoryName(face.Source)?.Replace('\\', '/');
                if (folder != null && !folders.Contains(folder)) folders.Add(folder);
            }
            foreach (var folder in folders)
            {
                var abs = Path.GetFullPath(folder);
                if (!Directory.Exists(abs)) continue;
                foreach (var licence in Directory.GetFiles(abs).Select(Path.GetFileName).Where(n => LicenceName.IsMatch(n) && !n.EndsWith(".meta", StringComparison.OrdinalIgnoreCase))
                             .OrderBy(n => n, StringComparer.Ordinal))
                {
                    var bytes = File.ReadAllBytes(Path.Combine(abs, licence));
                    var name = licence;
                    if (files.TryGetValue(name, out var taken))
                    {
                        if (taken.SequenceEqual(bytes)) continue;
                        name = Path.GetFileName(folder) + "-" + licence;
                        if (files.TryGetValue(name, out taken) && !taken.SequenceEqual(bytes))
                        {
                            errors.Add("two different licence files would be '" + name + "' in the kit; rename one of them");
                            continue;
                        }
                    }
                    files[name] = bytes;
                }
            }
            return files;
        }

        static string FontsCss(List<Face> faces)
        {
            var sb = new StringBuilder();
            sb.Append(Marker).Append('\n');
            foreach (var f in faces)
            {
                sb.Append("@font-face { font-family: \"").Append(CssString(f.Family)).Append("\"; ");
                if (f.Italic) sb.Append("font-style: italic; ");
                sb.Append("font-weight: ").Append(f.Weight.ToString(CultureInfo.InvariantCulture)).Append("; src: url(\"").Append(CssString(f.File)).Append("\")");
                var format = Format(f.File);
                if (format != null) sb.Append(" format(\"").Append(format).Append("\")");
                sb.Append("; }\n");
            }
            return sb.ToString();
        }

        static string Format(string file)
        {
            switch (Path.GetExtension(file).ToLowerInvariant())
            {
                case ".ttf": return "truetype";
                case ".otf": return "opentype";
                case ".ttc": return "collection";
                case ".woff": return "woff";
                case ".woff2": return "woff2";
                default: return null;
            }
        }

        static string CssString(string s) => (s ?? "").Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "").Replace("\r", "");

        /// <summary>fonts.json next to fonts.css: locale → family names in TMP's search order, keys sorted, LF.</summary>
        static string FontsJson(FontMap.FontsPlan plan)
        {
            var o = new JObject();
            foreach (var locale in plan.Locales.OrderBy(l => l, StringComparer.Ordinal))
                if (plan.LocaleFamilies.TryGetValue(locale, out var families))
                    o[locale] = new JArray(families.Cast<object>().ToArray());
            return o.ToString(Formatting.Indented).Replace("\r\n", "\n") + "\n";
        }

        /// <summary>kit.config.json with the profile's values; the original bytes when nothing changes (key order and other keys are kept).</summary>
        static byte[] UpdatedConfig(JObject config, byte[] original, DesignUiProfile profile, FontMap.FontsPlan plan)
        {
            var updated = (JObject)config.DeepClone();
            updated["reference"] = new JArray(profile.referenceResolution.x, profile.referenceResolution.y);
            updated["viewports"] = new JArray(profile.viewports.Select(v => (object)new JArray(v.x, v.y)).ToArray());
            updated["screenMatch"] = double.Parse(profile.screenMatch.ToString("R", CultureInfo.InvariantCulture), CultureInfo.InvariantCulture);
            updated["locales"] = new JArray(plan.Locales.Cast<object>().ToArray());
            if (updated["referenceLocale"] != null) updated["referenceLocale"] = plan.ReferenceLocale;
            return JToken.DeepEquals(config, updated) ? original : Utf8(updated.ToString(Formatting.None) + "\n");
        }

        static string KitRelative(JObject config, string key, string fallback, List<string> errors)
        {
            var token = config[key];
            var value = token == null ? fallback : token.Type == JTokenType.String ? token.Value<string>().Replace('\\', '/') : null;
            if (string.IsNullOrEmpty(value) || Path.IsPathRooted(value) || value.Split('/').Any(s => s == ".." || s.Length == 0))
            {
                errors.Add(ConfigFileName + " has an invalid \"" + key + "\": expected a path inside the kit folder");
                return null;
            }
            return value;
        }

        /// <summary>Writes when the content differs; generated text is compared with CRLF read as LF (a Windows checkout is not a change).</summary>
        static bool WriteIfChanged(string path, byte[] bytes, bool text)
        {
            if (File.Exists(path))
            {
                var old = File.ReadAllBytes(path);
                if (text ? Encoding.UTF8.GetString(old).Replace("\r\n", "\n") == Encoding.UTF8.GetString(bytes) : old.SequenceEqual(bytes)) return false;
            }
            var dir = Path.GetDirectoryName(path);
            if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
            File.WriteAllBytes(path, bytes);
            return true;
        }

        static byte[] Utf8(string text) => new UTF8Encoding(false).GetBytes(text.Replace("\r\n", "\n"));

        static string Fmt(double v) => v.ToString("R", CultureInfo.InvariantCulture);

        static KitSyncResult Failed(IEnumerable<string> errors, List<string> warnings, IReadOnlyList<string> twins = null) =>
            new KitSyncResult { Errors = errors.ToList(), Warnings = warnings, Twins = twins ?? new string[0] };
    }
