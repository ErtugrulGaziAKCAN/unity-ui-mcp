using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace DesignUi.Editor
{
    /// <summary>
    /// Writes the generated view class of a compiled screen (<c>&lt;Screen&gt;View.g.cs</c>, spec 9): one typed property
    /// per design element (its id in PascalCase; the screen root included), found once by element name in the
    /// constructor, which throws <see cref="InvalidOperationException"/> naming a missing element; the screen's states as
    /// <c>enum State</c> and <c>SetState</c>, which swaps the root's <c>state-&lt;name&gt;</c> class; and the runtime
    /// wiring UXML cannot declare: a <c>Clickable</c> on every element whose <c>:active</c> rules need one, and a
    /// <c>PseudoStateMirror</c> from an element to its shadow host.
    /// <para>The view names elements only (never the hashed <c>s-xxxxxxxx</c> style classes, which change with every style
    /// edit). Ids made by the exporter or the compiler (they contain <c>__</c>) are wired but not exposed. Repeat items
    /// (list templates and the template item of an inline repeat) belong to item views and are left out. Names that would
    /// clash (two ids with one PascalCase name, or a member the class itself declares) and an invalid namespace throw
    /// <see cref="IrFormatException"/>, so the compile fails before anything is written. The text is deterministic and
    /// uses \n line endings.</para>
    /// </summary>
    public static class ViewCodeWriter
    {
        const string ScreenToken = "$SCREEN$";

        const string Header =
            "// <auto-generated>\n" +
            "//     Generated by com.unity.design-ui from the design screen '" + ScreenToken + "'. Changes are overwritten by the next import;\n" +
            "//     the class is partial, so presenter code lives in another file.\n" +
            "// </auto-generated>\n";

        static readonly Regex Identifier = new Regex("^[A-Za-z_][A-Za-z0-9_]*$", RegexOptions.Compiled);

        static readonly HashSet<string> Keywords = new HashSet<string>(StringComparer.Ordinal)
        {
            "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue", "decimal",
            "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float", "for",
            "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock", "long", "namespace", "new", "null",
            "object", "operator", "out", "override", "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte",
            "sealed", "short", "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof",
            "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
        };

        /// <summary>Members the class declares or inherits from object: no element may take their name.</summary>
        static readonly string[] Reserved = { "State", "SetState", "Find", "StateClasses", "ScreenRoot", "Equals", "GetHashCode", "GetType", "ToString", "MemberwiseClone", "Finalize", "ReferenceEquals" };

        /// <param name="s">The compiled screen.</param>
        /// <param name="ns">The namespace (the profile's <c>generatedNamespace</c>).</param>
        /// <param name="className">The class name, <c>&lt;Screen&gt;View</c>.</param>
        public static string Write(CompiledScreen s, string ns, string className)
        {
            if (s == null) throw new ArgumentNullException(nameof(s));
            CheckNamespace(ns);
            if (string.IsNullOrEmpty(className) || !Identifier.IsMatch(className) || Keywords.Contains(className))
                throw new IrFormatException("'" + className + "' is not a valid C# class name for the view");

            var inScreen = ScreenElements(s);
            var exposed = inScreen.Where(e => e == s.Root || e.Name.IndexOf("__", StringComparison.Ordinal) < 0).ToList();
            var members = new Dictionary<string, string>(StringComparer.Ordinal); // member name -> element id
            foreach (var r in Reserved.Concat(new[] { className })) members[r] = null;
            var props = new List<(CompiledElement e, string member, string type)>();
            foreach (var e in exposed)
            {
                var member = Naming.Pascal(e.Name, "element id");
                if (members.TryGetValue(member, out var other))
                    throw new IrFormatException(other == null
                        ? "element id '" + e.Name + "' gives the view member '" + member + "', which the view class " + className + " already declares; rename the data-u-id"
                        : "element ids '" + other + "' and '" + e.Name + "' both give the view member '" + member + "'; rename one data-u-id");
                members[member] = e.Name;
                props.Add((e, member, TypeOf(e)));
            }

            var states = new List<(string name, string member)>();
            var stateMembers = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (var st in s.States.Count > 0 ? s.States : new[] { "default" })
            {
                var member = Naming.Pascal(st, "state");
                if (stateMembers.TryGetValue(member, out var other))
                    throw new IrFormatException("states '" + other + "' and '" + st + "' both give the State member '" + member + "'; rename one state");
                stateMembers[member] = st;
                states.Add((st, member));
            }

            var byName = props.ToDictionary(p => p.e.Name, p => p.member, StringComparer.Ordinal);
            string Ref(string name) => byName.TryGetValue(name, out var m) ? m : "Find<VisualElement>(root, " + Quote(name) + ")";

            var sb = new StringBuilder();
            sb.Append(Header.Replace(ScreenToken, s.ScreenId));
            sb.Append("using System;\n");
            sb.Append("using UnityEngine.UIElements;\n\n");
            sb.Append("namespace ").Append(ns).Append("\n{\n");
            sb.Append("    /// <summary>View of the design screen '").Append(Xml(s.ScreenId)).Append("': its elements by id, its states and its runtime wiring.</summary>\n");
            sb.Append("    public sealed partial class ").Append(className).Append("\n    {\n");
            sb.Append("        /// <summary>The screen's states; <see cref=\"SetState\"/> shows one.</summary>\n");
            sb.Append("        public enum State { ").Append(string.Join(", ", states.Select(x => x.member))).Append(" }\n\n");
            sb.Append("        /// <summary>The root class of each state, in <see cref=\"State\"/> order (the default state has none).</summary>\n");
            sb.Append("        static readonly string[] StateClasses = { ")
              .Append(string.Join(", ", states.Select(x => x.name == "default" ? "null" : Quote(ScreenBuilder.StateClassPrefix + x.name)))).Append(" };\n\n");
            sb.Append("        readonly VisualElement ScreenRoot;\n\n");
            foreach (var p in props)
                sb.Append("        public ").Append(p.type).Append(' ').Append(p.member).Append(" { get; }\n");
            sb.Append('\n');
            sb.Append("        /// <summary>Finds every element once below <paramref name=\"root\"/> (the screen's tree, or an element that contains it) and adds\n");
            sb.Append("        /// the manipulators the screen's rules need. Throws InvalidOperationException naming a missing element.</summary>\n");
            sb.Append("        public ").Append(className).Append("(VisualElement root)\n        {\n");
            sb.Append("            if (root == null) throw new ArgumentNullException(nameof(root));\n");
            foreach (var p in props)
                sb.Append("            ").Append(p.member).Append(" = Find<").Append(p.type).Append(">(root, ").Append(Quote(p.e.Name)).Append(");\n");
            sb.Append("            ScreenRoot = ").Append(Ref(s.Root.Name)).Append(";\n");
            foreach (var e in inScreen.Where(e => e.Clickable))
                sb.Append("            ").Append(Ref(e.Name)).Append(".AddManipulator(new Clickable(() => { }));\n");
            foreach (var host in inScreen.Where(e => e.MirrorHost && e.MirrorElement != null))
                sb.Append("            ").Append(Ref(host.MirrorElement)).Append(".AddManipulator(new global::DesignUi.PseudoStateMirror(Find<VisualElement>(root, ")
                  .Append(Quote(host.Name)).Append(")));\n");
            sb.Append("        }\n\n");
            sb.Append("        /// <summary>Shows a state: its class on the screen root, the other states' classes removed.</summary>\n");
            sb.Append("        public void SetState(State state)\n        {\n");
            sb.Append("            for (int i = 0; i < StateClasses.Length; i++)\n");
            sb.Append("                if (StateClasses[i] != null) ScreenRoot.EnableInClassList(StateClasses[i], i == (int)state);\n");
            sb.Append("        }\n\n");
            sb.Append("        static T Find<T>(VisualElement root, string name) where T : VisualElement\n        {\n");
            sb.Append("            var element = root.name == name ? root as T : root.Q<T>(name);\n");
            sb.Append("            if (element == null)\n");
            sb.Append("                throw new InvalidOperationException(\"").Append(className)
              .Append(": no \" + typeof(T).Name + \" named '\" + name + \"' below '\" + root.name + \"'; pass the screen's tree and recompile the screen when the design changed\");\n");
            sb.Append("            return element;\n        }\n");
            sb.Append("    }\n}\n");
            return sb.ToString();
        }

        /// <summary>The elements of the screen tree, without repeat items (their item views come with the repeat setters).</summary>
        static List<CompiledElement> ScreenElements(CompiledScreen s)
        {
            var items = new HashSet<CompiledElement>(s.Repeats.SelectMany(r => r.Items).SelectMany(i => i.DescendantsAndSelf()));
            var result = new List<CompiledElement>();
            void Visit(CompiledElement e)
            {
                if (items.Contains(e)) return;
                result.Add(e);
                foreach (var c in e.Children) Visit(c);
            }
            Visit(s.Root);
            return result;
        }

        static string TypeOf(CompiledElement e)
        {
            switch (e.Tag)
            {
                case "ui:VisualElement": return "VisualElement";
                case "ui:Label": return "Label";
                case "ui:Button": return "Button";
                case "ui:Toggle": return "Toggle";
                case "ui:TextField": return "TextField";
                case "ui:DropdownField": return "DropdownField";
                case "ui:ScrollView": return "ScrollView";
                case "ui:ListView": return "ListView";
                default: throw new IrFormatException("element '" + e.Name + "' has tag " + e.Tag + ", which the view writer does not know");
            }
        }

        static void CheckNamespace(string ns)
        {
            if (string.IsNullOrEmpty(ns) || ns.Split('.').Any(part => !Identifier.IsMatch(part) || Keywords.Contains(part)))
                throw new IrFormatException("'" + ns + "' is not a valid C# namespace for the generated view (the profile's generatedNamespace)");
        }

        /// <summary>A C# string literal (element names and state names are ASCII-checked by the compiler, but escape anyway).</summary>
        static string Quote(string value)
        {
            var sb = new StringBuilder("\"");
            foreach (var c in value)
            {
                switch (c)
                {
                    case '"': sb.Append("\\\""); break;
                    case '\\': sb.Append("\\\\"); break;
                    case '\n': sb.Append("\\n"); break;
                    case '\r': sb.Append("\\r"); break;
                    case '\t': sb.Append("\\t"); break;
                    default:
                        if (c < 0x20 || c > 0x7e) sb.Append("\\u").Append(((int)c).ToString("x4", System.Globalization.CultureInfo.InvariantCulture));
                        else sb.Append(c);
                        break;
                }
            }
            return sb.Append('"').ToString();
        }

        static string Xml(string value) => (value ?? "").Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("\n", " ").Replace("\r", " ");
    }
}
