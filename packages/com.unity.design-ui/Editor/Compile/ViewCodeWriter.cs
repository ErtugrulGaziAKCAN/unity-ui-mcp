using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace DesignUi.Editor
{
    /// <summary>
    /// Writes the generated view class of a compiled screen (<c>&lt;Screen&gt;View.g.cs</c>, spec 9), which a presenter drives
    /// with game data:
    /// <list type="bullet">
    /// <item>one typed property per design element (its id in PascalCase; the screen root included), found once by element
    /// name in the constructor, which throws InvalidOperationException naming a missing element;</item>
    /// <item>one setter per value name, <c>Set&lt;Name&gt;</c>: every <c>data-u-bind</c> of that name (a text through
    /// <see cref="DesignUi.DesignText"/>, so its first layout is kerned; an image's background) and every Smart String
    /// argument <c>{name}</c> of a design text. An unchanged value writes nothing and allocates nothing; an input
    /// (TextField, DropdownField) is compared with the value it shows, since the user edits it, and written without a
    /// change event;</item>
    /// <item>one <c>event Action &lt;Action&gt;Requested</c> per <c>data-u-action</c> (ids often equal their action, so the
    /// event names never take an element's name): a Button raises it from <c>clicked</c> (pointer, keyboard and gamepad),
    /// any other element from <c>ClickEvent</c>;</item>
    /// <item>the screen's states as <c>enum State</c> and <c>SetState</c>, which swaps the root's <c>state-&lt;name&gt;</c>
    /// class; <c>SetSelected</c>/<c>SetClass</c>, which toggle the design's <c>is-*</c> view-state classes (and their
    /// shadow hosts' copies); <c>SetEnabled</c>, Unity's enabled state, so the <c>:disabled</c> layers apply;</item>
    /// <item>one setter <c>Set&lt;Id&gt;Visible(bool visible)</c> per element the design's repeat items hide by markup in some
    /// items (<see cref="IrNode.ItemVisibility"/>: sample data, compiled shown), named from its <c>data-u-id</c>: it writes
    /// <see cref="DesignUi.DesignView.SetVisible"/> on the element that owns the visibility (the element, or its shadow
    /// host) and skips an unchanged value without allocating; never on an item root, whose display the repeat owns;</item>
    /// <item>one setter per <c>data-u-repeat</c>, <c>Set&lt;Repeat&gt;(int count, Action&lt;&lt;Repeat&gt;ItemView, int&gt; bind)</c>,
    /// with a nested item view class of the same members over the item template: inline repeats are pooled items in the
    /// container, list repeats a virtualized ListView. Repeats nest (an item view has the setters of the repeats in its
    /// item). An item view's events are cleared before each bind, so the bind callback subscribes them for its data;</item>
    /// <item>the runtime wiring UXML cannot declare: a <c>Clickable</c> on every element whose <c>:active</c> rules need
    /// one, and a <c>PseudoStateMirror</c> from an element to its shadow host.</item>
    /// </list>
    /// <para>The view names elements only (never the hashed <c>s-xxxxxxxx</c> style classes, which change with every style
    /// edit). Ids made by the exporter or the compiler (they contain <c>__</c>) are wired but not exposed. Names that would
    /// clash (two ids, values, actions or repeats with one member name, or a member the class itself declares) and an
    /// invalid namespace throw <see cref="IrFormatException"/>, so the compile fails before anything is written. The text
    /// is deterministic and uses \n line endings.</para>
    /// </summary>
    public static class ViewCodeWriter
    {
        const string ScreenToken = "$SCREEN$";
        const string Rt = "global::DesignUi.";

        const string Header =
            "// <auto-generated by com.unity.design-ui>\n" +
            "//     Generated from the design screen '" + ScreenToken + "'. Changes are overwritten by the next import; the classes are\n" +
            "//     partial, so presenter code lives in another file. Its assembly must reference DesignUi.Runtime.\n" +
            "// </auto-generated>\n";

        /// <summary>The suffix of an action's event: <c>open-inbox</c> raises <c>OpenInboxRequested</c>.</summary>
        public const string EventSuffix = "Requested";

        static readonly Regex Identifier = new Regex("^[A-Za-z_][A-Za-z0-9_]*$", RegexOptions.Compiled);

        static readonly HashSet<string> Keywords = new HashSet<string>(StringComparer.Ordinal)
        {
            "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue", "decimal",
            "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float", "for",
            "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock", "long", "namespace", "new", "null",
            "object", "operator", "out", "override", "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte",
            "sealed", "short", "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof",
            "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
        };

        static readonly string[] ObjectMembers = { "Equals", "GetHashCode", "GetType", "ToString", "MemberwiseClone", "Finalize", "ReferenceEquals" };

        /// <summary>Members a screen view declares besides its elements, values, actions and repeats.</summary>
        static readonly string[] ScreenMembers = { "State", "SetState", "Find", "StateClasses", "ScreenRoot", "SetSelected", "SetClass", "SetEnabled", "Animations" };

        /// <summary>Members an item view declares besides its elements, values, actions and repeats.</summary>
        static readonly string[] ItemMembers = { "Index", "BeginBind", "Find", "SetSelected", "SetClass", "SetEnabled" };

        /// <summary>The setter of the selection class.</summary>
        const string SelectedClass = "is-selected";

        // ---- the model ------------------------------------------------------------------------------------------------

        enum ValueKind { Text, Image }

        sealed class Value
        {
            public string Name;
            public string Member;
            public ValueKind Kind;
            public string Field;
            public readonly List<CompiledElement> Binds = new List<CompiledElement>();
            public readonly List<(ArgText text, int index)> Args = new List<(ArgText, int)>();
        }

        sealed class ArgText
        {
            public CompiledElement Element;
            public string Field;
            public string[] Names;
        }

        sealed class ActionEvent
        {
            public string Name;
            public string Member;
            public readonly List<CompiledElement> Elements = new List<CompiledElement>();
        }

        sealed class VisibilitySetter
        {
            public CompiledElement Element;
            public string Member;
            public string Field;
            /// <summary>The C# expression of the element that owns the visibility.</summary>
            public string Owner;
        }

        sealed class RepeatSetter
        {
            public CompiledRepeat Repeat;
            public string Member;
            public string ItemClass;
            public string Field;
            public View Item;
        }

        /// <summary>One generated class: the screen view, or an item view of a repeat.</summary>
        sealed class View
        {
            public string ClassName;
            /// <summary>The name used in messages (<c>SquadView</c>, <c>SquadView.PlayersItemView</c>).</summary>
            public string FullName;
            public CompiledRepeat Repeat;
            public bool IsItem => Repeat != null;
            public string Scope => IsItem ? "roots" : "root";
            public readonly List<CompiledElement> Elements = new List<CompiledElement>();
            public readonly List<(CompiledElement e, string member, string type)> Props = new List<(CompiledElement, string, string)>();
            public readonly Dictionary<string, string> ByName = new Dictionary<string, string>(StringComparer.Ordinal);
            public readonly List<Value> Values = new List<Value>();
            public readonly List<ArgText> ArgTexts = new List<ArgText>();
            public readonly List<ActionEvent> Actions = new List<ActionEvent>();
            public readonly List<RepeatSetter> Repeats = new List<RepeatSetter>();
            public readonly List<VisibilitySetter> Visibilities = new List<VisibilitySetter>();
            /// <summary>Member name to what claimed it (null: the class itself).</summary>
            public readonly Dictionary<string, string> Members = new Dictionary<string, string>(StringComparer.Ordinal);

            public void Claim(string member, string what)
            {
                if (Members.TryGetValue(member, out var other))
                    throw new IrFormatException(other == null
                        ? what + " gives the view member '" + member + "', which the view class " + FullName + " already declares; rename it"
                        : other + " and " + what + " both give the view member '" + member + "' of " + FullName + "; rename one");
                Members[member] = what;
            }

            /// <summary>The C# expression of an element in the constructor: its property, else a lookup.</summary>
            public string Ref(string name, string type = "VisualElement") =>
                ByName.TryGetValue(name, out var m) ? m : "Find<" + type + ">(" + Scope + ", " + Quote(name) + ")";

            /// <summary>Elements the setters write that the view does not expose: private fields found in the constructor.</summary>
            public readonly List<(string name, string type, string field)> Lookups = new List<(string, string, string)>();

            /// <summary>
            /// The C# expression of an element outside the constructor (a setter): its property, else a private field the
            /// constructor fills (<c>root</c> and <c>roots</c> are constructor parameters).
            /// </summary>
            public string Member(string name, string type = "VisualElement")
            {
                if (ByName.TryGetValue(name, out var m)) return m;
                foreach (var l in Lookups) if (l.name == name) return l.field;
                var field = "m_Element" + Lookups.Count;
                Lookups.Add((name, type, field));
                return field;
            }
        }

        /// <summary>The compile's element paths from the screen root (<c>root &gt; panel &gt; count</c>), for error messages; set by <see cref="Write"/>.</summary>
        [ThreadStatic] static Dictionary<CompiledElement, string> s_Paths;

        static string PathOf(CompiledElement e) => e != null && s_Paths != null && s_Paths.TryGetValue(e, out var p) ? p : e?.Name;

        /// <summary>
        /// The C# member part of a design name (<see cref="Naming.Pascal"/>); when it gives none, the error names the attribute,
        /// the name and the element's path (design-export lint rejects the same names, U-MRK-005).
        /// </summary>
        static string MemberOf(string name, string attribute, CompiledElement at)
        {
            try { return Naming.Pascal(name, attribute); }
            catch (IrFormatException e)
            {
                throw new IrFormatException(e.Message + (at != null ? " (on '" + PathOf(at) + "')" : "") +
                                            ": a name that becomes a generated C# member starts with a letter a-z; rename it in the design (an argument after what it " +
                                            "holds, e.g. {count}: a profile with indexed arguments numbers them itself)", e);
            }
        }

        /// <summary>Whether the screen has animation data (an element the animation player watches).</summary>
        static bool Animated(CompiledScreen s) => s.AllElements().Any(e => e.Classes.Contains(DesignUi.DesignAnimationData.MarkerClass));

        /// <param name="s">The compiled screen.</param>
        /// <param name="ns">The namespace (the profile's <c>generatedNamespace</c>).</param>
        /// <param name="className">The class name, <c>&lt;Screen&gt;View</c>.</param>
        public static string Write(CompiledScreen s, string ns, string className)
        {
            if (s == null) throw new ArgumentNullException(nameof(s));
            CheckNamespace(ns);
            if (string.IsNullOrEmpty(className) || !Identifier.IsMatch(className) || Keywords.Contains(className))
                throw new IrFormatException("'" + className + "' is not a valid C# class name for the view");

            s_Paths = new Dictionary<CompiledElement, string>();
            void Walk(CompiledElement e, string prefix)
            {
                var p = prefix == null ? e.Name : prefix + " > " + e.Name;
                s_Paths[e] = p;
                foreach (var c in e.Children) Walk(c, p);
            }
            if (s.Root != null) Walk(s.Root, null);
            try { return WriteViews(s, ns, className); }
            finally { s_Paths = null; }
        }

        static string WriteViews(CompiledScreen s, string ns, string className)
        {
            var itemRoots = new HashSet<CompiledElement>(s.Repeats.SelectMany(r => r.Items));
            var itemClasses = s.Repeats.Select(r => MemberOf(r.Name, "data-u-repeat", r.Items.FirstOrDefault()) + "ItemView").ToList();

            var screen = NewView(className, className, null, ScreenMembers, itemClasses);
            Collect(screen, new[] { s.Root }, itemRoots);
            var views = new List<View> { screen };
            foreach (var r in s.Repeats)
            {
                var itemClass = MemberOf(r.Name, "data-u-repeat", r.Items.FirstOrDefault()) + "ItemView";
                var item = NewView(itemClass, className + "." + itemClass, r, ItemMembers, itemClasses.Where(c => c != itemClass));
                item.Claim(className, "the screen view class");
                Collect(item, r.Items, itemRoots);
                views.Add(item);
            }
            // each repeat belongs to the view whose elements hold its container
            foreach (var r in s.Repeats)
            {
                var owner = views.FirstOrDefault(v => v.Elements.Any(e => e.Name == r.Container))
                            ?? throw new IrFormatException("the container '" + r.Container + "' of repeat '" + r.Name + "' is in no view");
                var item = views.Single(v => v.Repeat == r);
                var setter = new RepeatSetter
                {
                    Repeat = r, Member = "Set" + MemberOf(r.Name, "data-u-repeat", r.Items.FirstOrDefault()), ItemClass = item.ClassName,
                    Field = "m_Repeat" + owner.Repeats.Count, Item = item,
                };
                owner.Claim(setter.Member, "data-u-repeat '" + r.Name + "'");
                owner.Repeats.Add(setter);
            }
            foreach (var v in views)
            {
                Values(v);
                Actions(v);
                Visibilities(v);
            }

            var states = new List<(string name, string member)>();
            var stateMembers = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (var st in s.States.Count > 0 ? s.States : new[] { "default" })
            {
                var member = MemberOf(st, "data-u-state", null);
                if (stateMembers.TryGetValue(member, out var other))
                    throw new IrFormatException("states '" + other + "' and '" + st + "' both give the State member '" + member + "'; rename one state");
                stateMembers[member] = st;
                states.Add((st, member));
            }

            var sb = new StringBuilder();
            sb.Append(Header.Replace(ScreenToken, s.ScreenId));
            sb.Append("using System;\n");
            sb.Append("using UnityEngine.UIElements;\n\n");
            sb.Append("namespace ").Append(ns).Append("\n{\n");
            sb.Append("    /// <summary>View of the design screen '").Append(Xml(s.ScreenId)).Append("': its elements by id, values, actions, states, repeats and runtime wiring.</summary>\n");
            sb.Append("    public sealed partial class ").Append(className).Append("\n    {\n");
            sb.Append("        /// <summary>The screen's states; <see cref=\"SetState\"/> shows one.</summary>\n");
            sb.Append("        public enum State { ").Append(string.Join(", ", states.Select(x => x.member))).Append(" }\n\n");
            sb.Append("        /// <summary>The root class of each state, in <see cref=\"State\"/> order (the default state has none).</summary>\n");
            sb.Append("        static readonly string[] StateClasses = { ")
              .Append(string.Join(", ", states.Select(x => x.name == "default" ? "null" : Quote(ScreenBuilder.StateClassPrefix + x.name)))).Append(" };\n\n");
            sb.Append("        readonly VisualElement ScreenRoot;\n");
            if (Animated(s))
                sb.Append("\n        /// <summary>The screen's animation player (spec 11): it plays the transitions and keyframe animations by itself; set\n")
                  .Append("        /// ReducedMotion (a game's accessibility setting) or a clock here.</summary>\n")
                  .Append("        public ").Append(Rt).Append("DesignUiAnimationPlayer Animations { get; }\n");
            Body(sb, screen, s, "        ");
            sb.Append("\n        /// <summary>Shows a state: its class on the screen root, the other states' classes removed.</summary>\n");
            sb.Append("        public void SetState(State state)\n        {\n");
            sb.Append("            for (int i = 0; i < StateClasses.Length; i++)\n");
            sb.Append("                if (StateClasses[i] != null) ScreenRoot.EnableInClassList(StateClasses[i], i == (int)state);\n");
            sb.Append("        }\n");
            foreach (var item in views.Skip(1))
            {
                sb.Append('\n');
                sb.Append("        /// <summary>An item of the repeat '").Append(Xml(item.Repeat.Name)).Append("' (").Append(Xml(item.Repeat.TemplateFile ?? ""))
                  .Append("). Its events are cleared before each bind: subscribe them in the bind callback.</summary>\n");
                sb.Append("        public sealed partial class ").Append(item.ClassName).Append(" : ").Append(Rt).Append("IDesignRepeatItem\n        {\n");
                Body(sb, item, s, "            ");
                sb.Append("        }\n");
            }
            sb.Append("    }\n}\n");
            return sb.ToString();
        }

        static View NewView(string className, string fullName, CompiledRepeat repeat, IEnumerable<string> reserved, IEnumerable<string> nestedTypes)
        {
            var v = new View { ClassName = className, FullName = fullName, Repeat = repeat };
            foreach (var r in reserved.Concat(ObjectMembers).Concat(new[] { className })) v.Members[r] = null;
            foreach (var t in nestedTypes) if (!v.Members.ContainsKey(t)) v.Members[t] = "the item view class " + t;
            return v;
        }

        /// <summary>The view's elements: below its roots, without the items of any repeat (their item views have them).</summary>
        static void Collect(View v, IEnumerable<CompiledElement> roots, HashSet<CompiledElement> itemRoots)
        {
            var own = new HashSet<CompiledElement>(v.Repeat?.Items ?? new List<CompiledElement>());
            void Visit(CompiledElement e)
            {
                if (itemRoots.Contains(e) && !own.Contains(e)) return;
                v.Elements.Add(e);
                foreach (var c in e.Children) Visit(c);
            }
            foreach (var r in roots) Visit(r);
            foreach (var e in v.Elements)
            {
                if (!(e == v.Elements[0] && !v.IsItem) && e.Name.IndexOf("__", StringComparison.Ordinal) >= 0) continue;
                var member = MemberOf(e.Name, "data-u-id", e);
                v.Claim(member, "element id '" + e.Name + "'");
                v.ByName[e.Name] = member;
                v.Props.Add((e, member, TypeOf(e)));
            }
        }

        /// <summary>The view's value setters: binds and Smart String arguments by name, in document order.</summary>
        static void Values(View v)
        {
            var byName = new Dictionary<string, Value>(StringComparer.Ordinal);
            Value Get(string name, ValueKind kind, CompiledElement at, string attribute)
            {
                if (!byName.TryGetValue(name, out var value))
                {
                    value = new Value { Name = name, Member = "Set" + MemberOf(name, attribute, at), Kind = kind, Field = "m_Value" + byName.Count };
                    v.Claim(value.Member, "the value '" + name + "' (data-u-bind or argument)");
                    byName[name] = value;
                    v.Values.Add(value);
                }
                else if (value.Kind != kind)
                    throw new IrFormatException("the value '" + name + "' is bound to an image and to a text ('" + at.Name + "'); give them different names");
                return value;
            }
            foreach (var e in v.Elements)
            {
                var node = e.Source;
                if (node == null) continue;
                var args = node.Text?.Args;
                if (node.Bind != null)
                {
                    if (args != null && args.Length > 0)
                        throw new IrFormatException("'" + e.Name + "' has data-u-bind '" + node.Bind + "' and Smart String arguments (" + string.Join(", ", args) +
                                                    "); a bound value replaces the whole text. Bind the element or mark arguments in a localized text, not both");
                    var kind = BindKind(e);
                    var value = Get(node.Bind, kind, e, "data-u-bind");
                    value.Binds.Add(e);
                    v.Member(kind == ValueKind.Image ? Painter(e).Name : e.Name);
                }
                if (args != null && args.Length > 0)
                {
                    if (!IsText(e))
                        throw new IrFormatException("'" + e.Name + "' (" + e.Tag + ") has Smart String arguments but shows no text");
                    var text = new ArgText { Element = e, Field = "m_Args" + v.ArgTexts.Count, Names = args.Distinct(StringComparer.Ordinal).ToArray() };
                    v.ArgTexts.Add(text);
                    for (int i = 0; i < text.Names.Length; i++) Get(text.Names[i], ValueKind.Text, e, "data-u-arg").Args.Add((text, i));
                }
            }
        }

        /// <summary>
        /// The view's visibility setters: one per element the design's repeat items hide by markup in some items
        /// (<see cref="CompiledElement.VisibilityOwner"/>), named from its data-u-id, writing the element that owns the visibility.
        /// </summary>
        static void Visibilities(View v)
        {
            foreach (var e in v.Elements)
            {
                if (e.VisibilityOwner == null) continue;
                if (e.Name.IndexOf("__", StringComparison.Ordinal) >= 0)
                    throw new IrFormatException("'" + PathOf(e) + "' is shown in some of the design's repeat items and hidden by markup in others, but it has no data-u-id " +
                                                "(its name '" + e.Name + "' is structural): give it a data-u-id, which names its visibility setter (lint U-MRK-003)");
                if (v.IsItem && v.Repeat.Items.Any(i => i.Name == e.VisibilityOwner))
                    throw new IrFormatException("'" + PathOf(e) + "' is the root of an item of repeat '" + v.Repeat.Name + "', which alone shows and hides its items: " +
                                                "remove the item from the samples; for an empty nested list write no items in that sample (lint U-MRK-013)");
                var member = "Set" + MemberOf(e.Name, "data-u-id", e) + "Visible";
                v.Claim(member, "the visibility of element '" + e.Name + "'");
                v.Visibilities.Add(new VisibilitySetter { Element = e, Member = member, Field = "m_Visible" + v.Visibilities.Count, Owner = v.Member(e.VisibilityOwner) });
            }
        }

        static bool IsText(CompiledElement e) =>
            e.Tag == "ui:Label" || e.Tag == "ui:Button" || e.Tag == "ui:Toggle" || e.Tag == "ui:TextField" || e.Tag == "ui:DropdownField";

        /// <summary>A control whose value the user edits (its bound value is compared with what it shows, not with a cache).</summary>
        static bool IsValueControl(CompiledElement e) => e.Tag == "ui:TextField" || e.Tag == "ui:DropdownField";

        static ValueKind BindKind(CompiledElement e)
        {
            var node = e.Source;
            if (IsText(e))
            {
                if (e.Tag == "ui:Button" && node.Text == null && e.Children.Count > 0)
                    throw new IrFormatException("data-u-bind '" + node.Bind + "' is on button '" + e.Name + "', whose text is in its child elements; put data-u-bind on the text element");
                return ValueKind.Text;
            }
            if (node.Kind == "image" || node.Kind == "vector") return ValueKind.Image;
            throw new IrFormatException("data-u-bind '" + node.Bind + "' is on '" + e.Name + "' (a " + node.Kind + "), which shows no value; put data-u-bind on a text, button, toggle, input, dropdown or image");
        }

        /// <summary>The element that paints an image's picture: its content child (<c>&lt;id&gt;__image</c>), else itself.</summary>
        static CompiledElement Painter(CompiledElement e) => e.Children.FirstOrDefault(c => c.Name == e.Name + "__image") ?? e;

        static void Actions(View v)
        {
            var byName = new Dictionary<string, ActionEvent>(StringComparer.Ordinal);
            foreach (var e in v.Elements)
            {
                var action = e.Source?.Action;
                if (action == null) continue;
                if (!byName.TryGetValue(action, out var ev))
                {
                    ev = new ActionEvent { Name = action, Member = MemberOf(action, "data-u-action", e) + EventSuffix };
                    v.Claim(ev.Member, "data-u-action '" + action + "'");
                    byName[action] = ev;
                    v.Actions.Add(ev);
                }
                ev.Elements.Add(e);
            }
        }

        // ---- emitting ---------------------------------------------------------------------------------------------------

        static void Body(StringBuilder sb, View v, CompiledScreen s, string ind)
        {
            var inScope = new HashSet<CompiledElement>(v.Elements);
            var clickables = v.Elements.Where(e => e.Clickable).ToList();
            var pseudoHosts = v.Elements.Where(e => e.MirrorHost && e.MirrorElement != null).ToList();
            var classHosts = v.Elements.Where(e => e.MirrorElement != null && e.MirrorClasses.Count > 0).ToList();

            // fields (the context only where something reads it: an unread private field is a compiler warning)
            bool usesContext = v.Values.Count > 0 || v.ArgTexts.Count > 0 || v.Repeats.Count > 0;
            if (usesContext) sb.Append(ind).Append("readonly ").Append(Rt).Append("DesignViewContext m_Context;\n");
            sb.Append(ind).Append("readonly ").Append(Rt).Append("PseudoStateMirror[] m_PseudoMirrors;\n");
            sb.Append(ind).Append("readonly ").Append(Rt).Append("DesignClassMirror[] m_ClassMirrors;\n");
            foreach (var a in v.ArgTexts) sb.Append(ind).Append("readonly ").Append(Rt).Append("DesignTextArgs ").Append(a.Field).Append(";\n");
            foreach (var r in v.Repeats)
                sb.Append(ind).Append("readonly ").Append(Rt).Append(r.Repeat.Mode == "list" ? "DesignListRepeat<" : "DesignInlineRepeat<").Append(r.ItemClass).Append("> ").Append(r.Field).Append(";\n");
            foreach (var l in v.Lookups) sb.Append(ind).Append("readonly ").Append(l.type).Append(' ').Append(l.field).Append(";\n");
            foreach (var value in v.Values)
            {
                if (value.Kind == ValueKind.Text)
                {
                    if (value.Args.Count > 0 || value.Binds.Any(e => !IsValueControl(e))) sb.Append(ind).Append("string ").Append(value.Field).Append(";\n");
                }
                else
                {
                    sb.Append(ind).Append("Background ").Append(value.Field).Append(";\n");
                    sb.Append(ind).Append("bool ").Append(value.Field).Append("Set;\n");
                }
            }
            foreach (var vis in v.Visibilities) sb.Append(ind).Append("bool ").Append(vis.Field).Append(" = true;\n");
            sb.Append('\n');
            if (v.IsItem)
            {
                sb.Append(ind).Append("/// <summary>The index of the data this item shows, set before each bind (-1 before the first).</summary>\n");
                sb.Append(ind).Append("public int Index { get; private set; } = -1;\n\n");
            }
            foreach (var p in v.Props)
                sb.Append(ind).Append("public ").Append(p.type).Append(' ').Append(p.member).Append(" { get; }\n");
            foreach (var ev in v.Actions)
            {
                sb.Append('\n');
                sb.Append(ind).Append("/// <summary>Raised when the user activates ").Append(string.Join(", ", ev.Elements.Select(e => "'" + Xml(e.Name) + "'")))
                  .Append(" (data-u-action '").Append(Xml(ev.Name)).Append("').</summary>\n");
                sb.Append(ind).Append("public event Action ").Append(ev.Member).Append(";\n");
            }
            sb.Append('\n');

            // constructor
            if (v.IsItem)
            {
                sb.Append(ind).Append("/// <summary>Finds the item's elements below its root elements once and wires them.</summary>\n");
                sb.Append(ind).Append("internal ").Append(v.ClassName).Append("(VisualElement[] roots, ").Append(Rt).Append("DesignViewContext context)\n");
                sb.Append(ind).Append("{\n");
                if (usesContext) sb.Append(ind).Append("    m_Context = context;\n");
            }
            else
            {
                sb.Append(ind).Append("/// <summary>Finds every element once below <paramref name=\"root\"/> (the screen's tree, or an element that contains it) and adds\n");
                sb.Append(ind).Append("/// the manipulators and callbacks the screen needs: create one view per cloned tree. Throws InvalidOperationException naming a\n");
                sb.Append(ind).Append("/// missing element.</summary>\n");
                sb.Append(ind).Append("public ").Append(v.ClassName).Append("(VisualElement root)\n");
                sb.Append(ind).Append("{\n");
                sb.Append(ind).Append("    if (root == null) throw new ArgumentNullException(nameof(root));\n");
            }
            var b = ind + "    ";
            foreach (var p in v.Props)
                sb.Append(b).Append(p.member).Append(" = Find<").Append(p.type).Append(">(").Append(v.Scope).Append(", ").Append(Quote(p.e.Name)).Append(");\n");
            foreach (var l in v.Lookups)
                sb.Append(b).Append(l.field).Append(" = Find<").Append(l.type).Append(">(").Append(v.Scope).Append(", ").Append(Quote(l.name)).Append(");\n");
            if (!v.IsItem)
            {
                sb.Append(b).Append("ScreenRoot = ").Append(v.Ref(s.Root.Name)).Append(";\n");
                // the context also reports a root that is not a DesignScreen to a locale controller above it when it is attached
                sb.Append(b).Append(usesContext ? "m_Context = new " : "new ").Append(Rt).Append("DesignViewContext(ScreenRoot, ").Append(Quote(v.FullName)).Append(");\n");
                // the player a DesignScreen root attaches by itself; any other root gets it here
                if (Animated(s)) sb.Append(b).Append("Animations = ").Append(Rt).Append("DesignUiAnimationPlayer.Attach(ScreenRoot);\n");
            }
            foreach (var e in clickables)
                sb.Append(b).Append(v.Ref(e.Name)).Append(".AddManipulator(new Clickable(() => { }));\n");
            if (pseudoHosts.Count == 0) sb.Append(b).Append("m_PseudoMirrors = null;\n");
            else
            {
                sb.Append(b).Append("m_PseudoMirrors = new ").Append(Rt).Append("PseudoStateMirror[]\n").Append(b).Append("{\n");
                foreach (var host in pseudoHosts)
                    sb.Append(b).Append("    new ").Append(Rt).Append("PseudoStateMirror(").Append(v.Ref(host.Name)).Append("),\n");
                sb.Append(b).Append("};\n");
                for (int i = 0; i < pseudoHosts.Count; i++)
                    sb.Append(b).Append(v.Ref(pseudoHosts[i].MirrorElement)).Append(".AddManipulator(m_PseudoMirrors[").Append(i).Append("]);\n");
            }
            if (classHosts.Count == 0) sb.Append(b).Append("m_ClassMirrors = null;\n");
            else
            {
                sb.Append(b).Append("m_ClassMirrors = new ").Append(Rt).Append("DesignClassMirror[]\n").Append(b).Append("{\n");
                foreach (var host in classHosts)
                    sb.Append(b).Append("    new ").Append(Rt).Append("DesignClassMirror(").Append(v.Ref(host.MirrorElement)).Append(", ").Append(v.Ref(host.Name))
                      .Append(string.Concat(host.MirrorClasses.Select(c => ", " + Quote(c)))).Append("),\n");
                sb.Append(b).Append("};\n");
            }
            foreach (var ev in v.Actions)
                foreach (var e in ev.Elements)
                {
                    if (e.Tag == "ui:Button")
                        sb.Append(b).Append(v.Ref(e.Name, "Button")).Append(".clicked += () => ").Append(ev.Member).Append("?.Invoke();\n");
                    else
                        sb.Append(b).Append(v.Ref(e.Name)).Append(".RegisterCallback<ClickEvent>(_ => ").Append(ev.Member).Append("?.Invoke());\n");
                }
            foreach (var a in v.ArgTexts)
                sb.Append(b).Append(a.Field).Append(" = new ").Append(Rt).Append("DesignTextArgs(").Append(v.Ref(a.Element.Name)).Append(", m_Context")
                  .Append(string.Concat(a.Names.Select(n => ", " + Quote(n)))).Append(");\n");
            foreach (var r in v.Repeats)
            {
                var template = Quote(System.IO.Path.GetFileNameWithoutExtension(r.Repeat.TemplateFile ?? ""));
                var create = "r => new " + r.ItemClass + "(r, m_Context)";
                if (r.Repeat.Mode == "list")
                    sb.Append(b).Append(r.Field).Append(" = new ").Append(Rt).Append("DesignListRepeat<").Append(r.ItemClass).Append(">(")
                      .Append(v.Ref(r.Repeat.Container, "ListView")).Append(", m_Context.Template(").Append(template).Append("), ").Append(create).Append(");\n");
                else
                    sb.Append(b).Append(r.Field).Append(" = new ").Append(Rt).Append("DesignInlineRepeat<").Append(r.ItemClass).Append(">(")
                      .Append(v.Ref(r.Repeat.Container)).Append(", new[] { ").Append(string.Join(", ", r.Repeat.Items.Select(i => Quote(i.Name)))).Append(" }, m_Context.Template(")
                      .Append(template).Append("), ").Append(create).Append(");\n");
            }
            sb.Append(ind).Append("}\n");

            // item: the bind hook
            if (v.IsItem)
            {
                sb.Append('\n');
                sb.Append(ind).Append("void ").Append(Rt).Append("IDesignRepeatItem.BeginBind(int index)\n").Append(ind).Append("{\n");
                sb.Append(b).Append("Index = index;\n");
                foreach (var ev in v.Actions) sb.Append(b).Append(ev.Member).Append(" = null;\n");
                sb.Append(ind).Append("}\n");
            }

            // values
            foreach (var value in v.Values)
            {
                sb.Append('\n');
                var targets = value.Binds.Select(e => (value.Kind == ValueKind.Image ? "the image of '" : IsValueControl(e) ? "the value of '" : "the text of '") + Xml(e.Name) + "'")
                    .Concat(value.Args.Select(a => "{" + Xml(value.Name) + "} in the text of '" + Xml(a.text.Element.Name) + "'"));
                sb.Append(ind).Append("/// <summary>Sets the value '").Append(Xml(value.Name)).Append("': ").Append(string.Join("; ", targets))
                  .Append(value.Binds.Any(IsValueControl) ? ". An input is compared with the value it shows and written without a change event." : ". An unchanged value writes nothing.")
                  .Append("</summary>\n");
                if (value.Kind == ValueKind.Text)
                {
                    sb.Append(ind).Append("public void ").Append(value.Member).Append("(string value)\n").Append(ind).Append("{\n");
                    sb.Append(b).Append("if (value == null) value = \"\";\n");
                    // an input shows what the user typed: it is compared with its own value, and written without a change event
                    foreach (var e in value.Binds.Where(IsValueControl))
                        sb.Append(b).Append(Rt).Append("DesignView.SetValue(").Append(v.Member(e.Name)).Append(", value, m_Context);\n");
                    var texts = value.Binds.Where(e => !IsValueControl(e)).ToList();
                    if (texts.Count > 0 || value.Args.Count > 0)
                    {
                        sb.Append(b).Append("if (string.Equals(value, ").Append(value.Field).Append(", global::System.StringComparison.Ordinal)) return;\n");
                        sb.Append(b).Append(value.Field).Append(" = value;\n");
                    }
                    foreach (var e in texts)
                        sb.Append(b).Append(Rt).Append("DesignView.SetText(").Append(v.Member(e.Name)).Append(", value, m_Context);\n");
                    foreach (var (text, index) in value.Args)
                        sb.Append(b).Append(text.Field).Append(".Set(").Append(index).Append(", value);\n");
                }
                else
                {
                    sb.Append(ind).Append("public void ").Append(value.Member).Append("(Background value)\n").Append(ind).Append("{\n");
                    sb.Append(b).Append("if (").Append(value.Field).Append("Set && value == ").Append(value.Field).Append(") return;\n");
                    sb.Append(b).Append(value.Field).Append("Set = true;\n");
                    sb.Append(b).Append(value.Field).Append(" = value;\n");
                    foreach (var e in value.Binds)
                        sb.Append(b).Append(Rt).Append("DesignView.SetImage(").Append(v.Member(Painter(e).Name)).Append(", value);\n");
                }
                sb.Append(ind).Append("}\n");
            }

            // visibility: the design's items hide these by markup in some items; compiled shown
            foreach (var vis in v.Visibilities)
            {
                sb.Append('\n');
                sb.Append(ind).Append("/// <summary>Shows or hides '").Append(Xml(vis.Element.Name)).Append('\'').Append(v.IsItem ? " in this item" : "")
                  .Append(" (the design's items hide it by markup in some of them). An unchanged value writes nothing.</summary>\n");
                sb.Append(ind).Append("public void ").Append(vis.Member).Append("(bool visible)\n").Append(ind).Append("{\n");
                sb.Append(b).Append("if (visible == ").Append(vis.Field).Append(") return;\n");
                sb.Append(b).Append(vis.Field).Append(" = visible;\n");
                sb.Append(b).Append(Rt).Append("DesignView.SetVisible(").Append(vis.Owner).Append(", visible);\n");
                sb.Append(ind).Append("}\n");
            }

            // repeats
            foreach (var r in v.Repeats)
            {
                sb.Append('\n');
                sb.Append(ind).Append("/// <summary>Shows <paramref name=\"count\"/> items of the repeat '").Append(Xml(r.Repeat.Name)).Append("' (")
                  .Append(r.Repeat.Mode == "list" ? "a virtualized ListView: <paramref name=\"bind\"/> runs for each item it shows, also while scrolling" : "pooled items: <paramref name=\"bind\"/> runs for each item, in order")
                  .Append(").</summary>\n");
                sb.Append(ind).Append("public void ").Append(r.Member).Append("(int count, Action<").Append(r.ItemClass).Append(", int> bind) => ")
                  .Append(r.Field).Append(".SetItems(count, bind);\n");
            }

            // classes and enabled state
            sb.Append('\n');
            sb.Append(ind).Append("/// <summary>Adds or removes the design's selection class (").Append(SelectedClass).Append(") on <paramref name=\"element\"/>.</summary>\n");
            sb.Append(ind).Append("public void SetSelected(VisualElement element, bool selected) => SetClass(element, ").Append(Quote(SelectedClass)).Append(", selected);\n\n");
            sb.Append(ind).Append("/// <summary>Adds or removes a view-state class of the design (is-*) on <paramref name=\"element\"/> and on the shadow hosts that mirror it.</summary>\n");
            sb.Append(ind).Append("public void SetClass(VisualElement element, string className, bool on) => ").Append(Rt).Append("DesignView.SetClass(element, className, on, m_ClassMirrors);\n\n");
            sb.Append(ind).Append("/// <summary>Enables or disables <paramref name=\"element\"/> (the design's :disabled layers apply), its shadow hosts at once.</summary>\n");
            sb.Append(ind).Append("public void SetEnabled(VisualElement element, bool enabled) => ").Append(Rt).Append("DesignView.SetEnabled(element, enabled, m_PseudoMirrors);\n\n");

            // lookup
            if (v.IsItem)
                sb.Append(ind).Append("static T Find<T>(VisualElement[] roots, string name) where T : VisualElement => ").Append(Rt).Append("DesignView.Find<T>(roots, name, ")
                  .Append(Quote(v.FullName)).Append(");\n");
            else
                sb.Append(ind).Append("static T Find<T>(VisualElement root, string name) where T : VisualElement => ").Append(Rt).Append("DesignView.Find<T>(root, name, ")
                  .Append(Quote(v.FullName)).Append(");\n");
        }

        static string TypeOf(CompiledElement e)
        {
            switch (e.Tag)
            {
                case "ui:VisualElement": return "VisualElement";
                case ScreenBuilder.ScreenTag: return "VisualElement";
                case "ui:Label": return "Label";
                case "ui:Button": return "Button";
                case "ui:Toggle": return "Toggle";
                case "ui:TextField": return "TextField";
                case "ui:DropdownField": return "DropdownField";
                case "ui:ScrollView": return "ScrollView";
                case "ui:ListView": return "ListView";
                default: throw new IrFormatException("element '" + e.Name + "' has tag " + e.Tag + ", which the view writer does not know");
            }
        }

        static void CheckNamespace(string ns)
        {
            if (string.IsNullOrEmpty(ns) || ns.Split('.').Any(part => !Identifier.IsMatch(part) || Keywords.Contains(part)))
                throw new IrFormatException("'" + ns + "' is not a valid C# namespace for the generated view (the profile's generatedNamespace)");
        }

        /// <summary>A C# string literal (element names and state names are ASCII-checked by the compiler, but escape anyway).</summary>
        static string Quote(string value)
        {
            var sb = new StringBuilder("\"");
            foreach (var c in value)
            {
                switch (c)
                {
                    case '"': sb.Append("\\\""); break;
                    case '\\': sb.Append("\\\\"); break;
                    case '\n': sb.Append("\\n"); break;
                    case '\r': sb.Append("\\r"); break;
                    case '\t': sb.Append("\\t"); break;
                    default:
                        if (c < 0x20 || c > 0x7e) sb.Append("\\u").Append(((int)c).ToString("x4", System.Globalization.CultureInfo.InvariantCulture));
                        else sb.Append(c);
                        break;
                }
            }
            return sb.Append('"').ToString();
        }

        static string Xml(string value) => (value ?? "").Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("\n", " ").Replace("\r", " ");
    }
