using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace DesignUi.Editor
{
    /// <summary>
    /// A shadow host and its element. When the host has the <c>dui-mirror-host</c> class the view attaches a
    /// PseudoStateMirror to the element targeting the host; <c>classes</c> (null when none) are the element's <c>is-*</c>
    /// classes the view toggles on the host together with the element.
    /// </summary>
    public sealed class MirrorEntry
    {
        public string element;
        public string host;
        public string[] classes;
    }

    /// <summary>An attribute text UI Toolkit does not draw (alt, aria-label): its localization key and texts.</summary>
    public sealed class AccessibilityText
    {
        public string key;
        public string tr;
        public string en;
    }

    /// <summary>A repeat: container, mode, list-mode template file and item names.</summary>
    public sealed class RepeatEntry
    {
        public string name;
        public string mode;
        public string container;
        public string template;
        public string[] items = new string[0];
    }

    /// <summary>
    /// <c>.design-ui.json</c> next to a screen's generated files (spec 8): source, IR and generator identity, the hash of
    /// every generated file (the manual-edit guard and the incremental writer compare against them), and what the view
    /// must wire at runtime because UXML cannot declare it. Written with sorted keys and \n line endings.
    /// </summary>
    public sealed class GeneratedManifest
    {
        public string screen;
        public string sourceSha256;
        public string irSha256;
        public string generatorVersion;
        /// <summary>
        /// The package that generated the files (<see cref="PackageStamp"/>): a screen generated by another package version may
        /// need what this one does not have, and its assets need importing again after a package update.
        /// </summary>
        public string packageStamp;
        /// <summary>
        /// File path relative to the manifest's folder to the SHA-256 (lowercase hex) of its content: the bytes of a binary
        /// file, the bytes with CRLF read as LF for a text file (a Windows checkout with autocrlf is not an edit).
        /// </summary>
        public Dictionary<string, string> files = new Dictionary<string, string>(StringComparer.Ordinal);
        public string[] removedElements = new string[0];
        /// <summary>Name of the screen root element, which carries the <c>state-*</c> and <c>bp-*</c> classes.</summary>
        public string root;
        /// <summary>Reserved name of the generated view class file (<c>&lt;Screen&gt;View.g.cs</c>), written only when its text changes.</summary>
        public string view;
        /// <summary>Elements that need a Clickable from the view so that :active applies (UXML cannot declare manipulators).</summary>
        public string[] clickable = new string[0];
        public MirrorEntry[] mirrors = new MirrorEntry[0];
        public RepeatEntry[] repeats = new RepeatEntry[0];
        /// <summary>
        /// Element name to the element its view setter <c>Set&lt;Id&gt;Visible</c> shows and hides (itself, or its shadow host),
        /// for every element the design's repeat items hide by markup in some items; null when the screen has none.
        /// </summary>
        public Dictionary<string, string> visibility;
        /// <summary>
        /// Element name to its undrawn attribute texts (<c>alt</c>, <c>aria-label</c>) by attribute name; null when the
        /// screen has none.
        /// </summary>
        public Dictionary<string, Dictionary<string, AccessibilityText>> accessibility;
        /// <summary>
        /// The font faces the screen's texts render with (<c>400</c>, <c>700 italic</c>, …): every screen's are kept as twins
        /// (<see cref="FontMap.ProfileFaces"/>). Null in the shared manifest and in one written before faces were recorded.
        /// </summary>
        public string[] faces;
        /// <summary>Shared manifest only: the union of all screens' tokens (USS variable name to value).</summary>
        public Dictionary<string, string> tokens;
        /// <summary>Shared manifest only: screen folder name to the screen id compiled into it.</summary>
        public Dictionary<string, string> screens;

        /// <summary>The manifest at <paramref name="path"/>, or null when there is none. Throws InvalidDataException when it is unreadable.</summary>
        public static GeneratedManifest Load(string path)
        {
            if (!File.Exists(path)) return null;
            GeneratedManifest m;
            try { m = JsonConvert.DeserializeObject<GeneratedManifest>(File.ReadAllText(path)); }
            catch (JsonException e) { throw new InvalidDataException("generated manifest '" + path + "' is not valid: " + e.Message, e); }
            if (m == null) throw new InvalidDataException("generated manifest '" + path + "' is empty");
            m.files = m.files == null ? new Dictionary<string, string>(StringComparer.Ordinal) : new Dictionary<string, string>(m.files, StringComparer.Ordinal);
            m.removedElements = m.removedElements ?? new string[0];
            m.clickable = m.clickable ?? new string[0];
            m.mirrors = m.mirrors ?? new MirrorEntry[0];
            m.repeats = m.repeats ?? new RepeatEntry[0];
            return m;
        }

        public void Save(string path) => File.WriteAllText(path, ToJson(), new UTF8Encoding(false));

        /// <summary>The manifest text: sorted keys, two-space indentation, \n line endings, null fields left out.</summary>
        public string ToJson()
        {
            var serializer = JsonSerializer.Create(new JsonSerializerSettings { NullValueHandling = NullValueHandling.Ignore });
            var token = Sort(JToken.FromObject(this, serializer));
            using (var sw = new StringWriter { NewLine = "\n" })
            {
                using (var writer = new JsonTextWriter(sw) { Formatting = Formatting.Indented, Indentation = 2 })
                    token.WriteTo(writer);
                return sw.ToString().Replace("\r\n", "\n") + "\n";
            }
        }

        static JToken Sort(JToken t)
        {
            if (t is JObject o)
                return new JObject(o.Properties().OrderBy(p => p.Name, StringComparer.Ordinal).Select(p => new JProperty(p.Name, Sort(p.Value))));
            if (t is JArray a) return new JArray(a.Select(Sort));
            return t;
        }

        /// <summary>
        /// Generated files under <paramref name="outDir"/> whose content no longer matches its recorded hash, i.e. that were
        /// edited by hand. A missing file is not an edit (it is written again), and text compares with CRLF read as LF.
        /// Paths are <c>outDir/relative</c>.
        /// </summary>
        public IReadOnlyList<string> FindManualEdits(string outDir)
        {
            var result = new List<string>();
            foreach (var kv in files.OrderBy(k => k.Key, StringComparer.Ordinal))
            {
                var path = Combine(outDir, kv.Key);
                if (File.Exists(path) && !string.Equals(ContentHash(kv.Key, File.ReadAllBytes(path)), kv.Value, StringComparison.OrdinalIgnoreCase))
                    result.Add(path);
            }
            return result;
        }

        static readonly HashSet<string> TextExtensions = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
            { ".uxml", ".uss", ".tss", ".cs", ".json", ".svg", ".txt", ".md", ".gitattributes" };

        /// <summary>Whether a generated file is text (compared and hashed with CRLF read as LF); everything else is binary.</summary>
        public static bool IsText(string path)
        {
            var name = Path.GetFileName(path);
            return TextExtensions.Contains(name.StartsWith(".", StringComparison.Ordinal) && name.IndexOf('.', 1) < 0 ? name : Path.GetExtension(name));
        }

        /// <summary>The bytes a file's hash and comparisons use: unchanged for binary files, CRLF as LF for text.</summary>
        public static byte[] Normalized(string path, byte[] bytes)
        {
            if (!IsText(path) || Array.IndexOf(bytes, (byte)'\r') < 0) return bytes;
            var result = new List<byte>(bytes.Length);
            for (int i = 0; i < bytes.Length; i++)
                if (!(bytes[i] == (byte)'\r' && i + 1 < bytes.Length && bytes[i + 1] == (byte)'\n')) result.Add(bytes[i]);
            return result.ToArray();
        }

        /// <summary>SHA-256 of a file's normalized content (see <see cref="Normalized"/>).</summary>
        public static string ContentHash(string path, byte[] bytes) => Sha256Hex(Normalized(path, bytes));

        /// <summary>Whether two versions of a file have the same normalized content.</summary>
        public static bool SameContent(string path, byte[] a, byte[] b) => Normalized(path, a).SequenceEqual(Normalized(path, b));

        internal static string Combine(string dir, string relative) => dir.TrimEnd('/', '\\') + "/" + relative;

        public static string Sha256Hex(byte[] bytes)
        {
            using (var sha = SHA256.Create())
            {
                var hash = sha.ComputeHash(bytes);
                var sb = new StringBuilder(hash.Length * 2);
                foreach (var b in hash) sb.Append(b.ToString("x2", System.Globalization.CultureInfo.InvariantCulture));
                return sb.ToString();
            }
        }
    }
}
