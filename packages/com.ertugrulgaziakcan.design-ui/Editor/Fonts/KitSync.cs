    public sealed class KitSyncResult
    {
        public bool Ok => Errors.Count == 0;
        /// <summary>Kit files the sync owns, relative to the kit folder with '/' separators.</summary>
        public IReadOnlyList<string> Files = new string[0];
        /// <summary>The files of <see cref="Files"/> whose content changed and were written in this run.</summary>
        public IReadOnlyList<string> Written = new string[0];
        /// <summary>Asset paths of the locales' UI Toolkit font twins (created or updated as needed).</summary>
        public IReadOnlyList<string> Twins = new string[0];
        /// <summary>The faces that got twins: each locale font's own and the weight-table faces the kit's text styles use ("family weight (TMP asset)").</summary>
        public IReadOnlyList<string> Faces = new string[0];
        /// <summary>Weight-table faces of the locale fonts that get no twin (no text style or compiled screen uses them).</summary>
        public int SkippedFaces;
        /// <summary>Twin files deleted because no text style, compiled screen or locale font uses them any more.</summary>
        public IReadOnlyList<string> RemovedTwins = new string[0];
        public IReadOnlyList<string> Warnings = new string[0];
        /// <summary>Why the sync stopped; nothing is written into the kit and no twin is touched when there are errors.</summary>
        public IReadOnlyList<string> Errors = new string[0];
        /// <summary>Information for the log, e.g. how a relative kit folder was resolved.</summary>
        public IReadOnlyList<string> Notes = new string[0];
        /// <summary>The kit folder the sync used (absolute).</summary>
        public string KitDir;
    }

    /// <summary>
    /// Font sync (spec 5.1, 6): the Unity project is the source of truth. For the profile's locales (reference first) it
    /// resolves the TMP fonts, checks the kit's text styles against the face metrics of the reference locale's twin
    /// (docs/findings/m0.md: line height and text styles, bold policy), creates or updates the UI Toolkit twins, and writes
    /// into the kit folder:
    /// <list type="bullet">
    /// <item><c>fonts/&lt;file&gt;</c>: the source TTF/OTF of every font TMP searches for a locale, with the licence files next to it;</item>
    /// <item><c>fonts/fonts.css</c>: one <c>@font-face</c> per family and weight (family = the TMP face's family name; weights from the TMP weight table);</item>
    /// <item><c>fonts/fonts.json</c>: locale → families, in TMP's search order;</item>
    /// <item><c>kit.config.json</c>: <c>reference</c>, <c>viewports</c>, <c>screenMatch</c> and <c>locales</c> from the profile; other keys are kept;</item>
    /// <item><c>tokens.css</c> (when the kit has one): each <c>--font-*</c> token names a synced family (<see cref="KitFontTokens"/>); a
    /// token that maps to none is reported and kept.</item>
    /// </list>
    /// The paths of <c>fonts.css</c> and the text styles come from <c>kit.config.json</c>; a relative kit folder is
    /// resolved against the Unity project root (and noted). Every check runs before any write: a failed sync changes no
    /// twin and no kit file. Files are written only when their content changes; files in the fonts folder that no locale
    /// uses are reported, not deleted.
    /// </summary>
    public static class KitSync
    {
        public const string ConfigFileName = "kit.config.json";

        const string Marker = "/* auto-generated by com.ertugrulgaziakcan.design-ui: the Unity project's TMP fonts per locale (kit sync) */";

        /// <summary>A licence file for every font in its folder (OFL.txt, LICENSE, …).</summary>
        static readonly Regex LicenceName = new Regex(@"^(ofl|licen[cs]e|copying|notice)([._ -].*)?$", RegexOptions.Compiled | RegexOptions.IgnoreCase);

        /// <summary>A licence file of one font family (RobotoMono-LICENSE.txt): group 1 is the family prefix.</summary>
        static readonly Regex PrefixedLicence = new Regex(@"^(.+?)[._ -](ofl|licen[cs]e|copying|notice)([._ -].*)?$", RegexOptions.Compiled | RegexOptions.IgnoreCase);

        public static KitSyncResult Run(DesignUiProfile profile, string kitDir, IFontResolver resolver)
        {
            var errors = new List<string>();
            var warnings = new List<string>();
            var notes = new List<string>();
            if (profile == null) return Failed(new[] { "no DesignUiProfile" }, warnings, notes);
            try { resolver = resolver ?? FontMap.ResolverFor(profile); }
            catch (FontSetupException e) { return Failed(new[] { e.Message }, warnings, notes); }
            if (string.IsNullOrEmpty(kitDir)) return Failed(new[] { "no kit folder" }, warnings, notes);
            if (!Path.IsPathRooted(kitDir))
            {
                var resolved = Path.GetFullPath(Path.Combine(ProjectRoot, kitDir));
                notes.Add("the kit folder '" + kitDir + "' is relative: resolved against the Unity project root to '" + resolved + "'");
                kitDir = resolved;
            }
            kitDir = kitDir.Replace('\\', '/').TrimEnd('/');
            if (!Directory.Exists(kitDir)) return Failed(new[] { "the kit folder '" + kitDir + "' does not exist" }, warnings, notes, kitDir);

            // ---- the kit's configuration -------------------------------------------------------------------------------
            byte[] configBytes;
            JObject config;
            try
            {
                configBytes = File.ReadAllBytes(kitDir + "/" + ConfigFileName);
                config = JObject.Parse(Encoding.UTF8.GetString(configBytes));
            }
            catch (Exception e) when (e is IOException || e is UnauthorizedAccessException || e is JsonException)
            {
                return Failed(new[] { "cannot read " + ConfigFileName + " in the kit folder '" + kitDir + "': " + e.Message }, warnings, notes, kitDir);
            }
            var fontsCss = KitRelative(config, "fontsCss", "fonts/fonts.css", errors);
            var textStyles = KitRelative(config, "textStyles", "text-styles.json", errors);
            var tokensCss = KitRelative(config, "tokensCss", "tokens.css", errors);
            if (profile.referenceResolution.x <= 0 || profile.referenceResolution.y <= 0) errors.Add("the DesignUiProfile's reference resolution must be positive");
            if (profile.viewports == null || profile.viewports.Length == 0 || profile.viewports.Any(v => v.x <= 0 || v.y <= 0))
                errors.Add("the DesignUiProfile needs at least one viewport, each with a positive size");

            var settings = FindTmpSettingsAssets();
            if (settings.Count > 1) warnings.Add("Multiple TMP Settings assets under Resources: " + string.Join(", ", settings));

            // ---- fonts per locale (nothing is written before everything checks out) -------------------------------------
            FontMap.FontsPlan plan;
            try { plan = FontMap.Plan(profile, resolver); }
            catch (FontSetupException e) { return Failed(new[] { e.Message }, warnings, notes, kitDir); } // a project resolver that throws
            var fellBack = FontMap.FallbackNote(resolver);
            if (fellBack != null) warnings.Add(fellBack);
            errors.AddRange(plan.Errors);
            foreach (var locale in plan.Missing) errors.Add("Font not resolvable: " + FontMap.NoFont(locale));
            if (errors.Count > 0) return Failed(errors, warnings, notes, kitDir);

            // ---- every check before any write: faces and files, text styles against the twins' face metrics -------------
            var faces = Faces(plan, errors);
            var scales = (profile.viewports ?? new UnityEngine.Vector2Int[0]).Where(v => v.x > 0 && v.y > 0)
                .Select(v => (v, BoxesWriter.Scale(v, profile.referenceResolution, profile.screenMatch))).ToList();
            errors.AddRange(ValidateTextStyles(kitDir + "/" + textStyles, plan.Fonts[plan.ReferenceLocale].Primary, scales));
            var readability = errors.Count == 0 ? ReadabilityWarning(kitDir + "/" + textStyles, scales) : null;
            if (readability != null) warnings.Add(readability);
            // every line box of the table and of its text-size steps: the twins an import makes (and keeps)
            if (errors.Count == 0) plan.LineBoxes = ScreenCompiler.ScaledLineBoxes(KitTextStyles.LineBoxesOf(kitDir + "/" + textStyles), profile.textSizes);
            // twins only for the faces the text styles and the compiled screens use (an import adds a new design's own)
            plan.Faces = FontMap.ProfileFaces(profile, kitDir + "/" + textStyles);
            var copies = errors.Count == 0 ? FontFiles(faces, errors) : null;
            KitFontTokens.Result tokens = null;
            byte[] tokensBytes = null;
            try
            {
                if (errors.Count == 0 && File.Exists(kitDir + "/" + tokensCss))
                {
                    tokensBytes = File.ReadAllBytes(kitDir + "/" + tokensCss);
                    tokens = KitFontTokens.Apply(Utf8Text(tokensBytes), plan);
                }
            }
            catch (Exception e) when (e is IOException || e is UnauthorizedAccessException) { errors.Add("cannot read " + tokensCss + " in the kit folder '" + kitDir + "': " + e.Message); }
            if (errors.Count > 0) return Failed(errors, warnings, notes, kitDir);

            // ---- UI Toolkit twins (own fallbacks, then the global ones) --------------------------------------------------
            FontTwinGenerator.TwinRun twins;
            try { twins = FontMap.EnsureTwins(plan); }
            catch (FontSetupException e) { return Failed(new[] { e.Message }, warnings, notes, kitDir); }
            warnings.AddRange(twins.Notes);
            var twinPaths = twins.Twins.Values.Select(AssetDatabase.GetAssetPath).Distinct().OrderBy(p => p, StringComparer.Ordinal).ToList();
            // twins of faces, line boxes and fonts nothing uses any more leave the folder
            var pruned = TwinPrune.Run(profile, plan, twins, kitDir);
            if (pruned.Skipped != null) warnings.Add(pruned.Skipped);

            // ---- kit outputs ---------------------------------------------------------------------------------------------
            var fontsDir = Path.GetDirectoryName(fontsCss)?.Replace('\\', '/') ?? "";
            string InFonts(string name) => fontsDir.Length > 0 ? fontsDir + "/" + name : name;
            var outputs = new SortedDictionary<string, byte[]>(StringComparer.Ordinal);
            foreach (var kv in copies) outputs[InFonts(kv.Key)] = kv.Value;
            var fontsJson = Regex.Replace(fontsCss, @"\.css$", "", RegexOptions.IgnoreCase) + ".json";
            outputs[fontsCss] = Utf8(FontsCss(faces));
            outputs[fontsJson] = Utf8(FontsJson(plan));
            outputs[ConfigFileName] = UpdatedConfig(config, configBytes, profile, plan);
            var text = new HashSet<string>(StringComparer.Ordinal) { fontsCss, fontsJson, ConfigFileName };
            // the font tokens name the synced families, so designs that use them pass lint against fonts.css
            if (tokens != null)
            {
                // a hand-authored file: unchanged bytes when no token changes, else the same text with its BOM and line endings
                outputs[tokensCss] = tokens.Text == Utf8Text(tokensBytes) ? tokensBytes : Preamble(tokensBytes).Concat(new UTF8Encoding(false).GetBytes(tokens.Text)).ToArray();
                warnings.AddRange(tokens.Changed);
                warnings.AddRange(tokens.Unmapped);
                notes.AddRange(tokens.Recased);
            }

            var written = new List<string>();
            try
            {
                foreach (var kv in outputs)
                    if (WriteIfChanged(kitDir + "/" + kv.Key, kv.Value, text.Contains(kv.Key))) written.Add(kv.Key);
            }
            catch (Exception e) when (e is IOException || e is UnauthorizedAccessException)
            {
                return new KitSyncResult
                {
                    Files = outputs.Keys.ToList(), Written = written, Twins = twinPaths, Warnings = warnings, Notes = notes, KitDir = kitDir,
                    Errors = new[] { "writing the kit failed: " + e.Message },
                };
            }

            var fontsAbs = fontsDir.Length > 0 ? kitDir + "/" + fontsDir : kitDir;
            if (fontsDir.Length > 0 && Directory.Exists(fontsAbs))
            {
                var unknown = Directory.GetFiles(fontsAbs).Select(Path.GetFileName)
                    .Where(n => !n.StartsWith(".", StringComparison.Ordinal) && !n.EndsWith(".meta", StringComparison.Ordinal) && !outputs.ContainsKey(InFonts(n)))
                    .OrderBy(n => n, StringComparer.Ordinal).ToList();
                if (unknown.Count > 0)
                    warnings.Add("the kit's " + fontsDir + "/ folder has files no locale font uses: " + string.Join(", ", unknown) + " (left in place; delete them if they are stale)");
            }
            return new KitSyncResult
            {
                Files = outputs.Keys.ToList(), Written = written, Twins = twinPaths, Warnings = warnings, Notes = notes, KitDir = kitDir,
                Faces = FontMap.ChosenFaces(plan), SkippedFaces = FontMap.SkippedFaces(plan), RemovedTwins = pruned.Deleted,
            };
        }

        /// <summary>
        /// TMP Settings assets <c>Resources.Load("TMP Settings")</c> can reach (named "TMP Settings", directly in a
        /// Resources folder), sorted. More than one makes the settings TMP uses depend on load order.
        /// </summary>
        public static IReadOnlyList<string> FindTmpSettingsAssets() =>
            AssetDatabase.FindAssets("t:" + nameof(TMP_Settings))
                .Select(AssetDatabase.GUIDToAssetPath)
                .Where(p => Path.GetFileNameWithoutExtension(p) == "TMP Settings" && Path.GetFileName(Path.GetDirectoryName(p)) == "Resources")
                .Distinct()
                .OrderBy(p => p, StringComparer.Ordinal)
                .ToList();

        // ---- text styles (docs/findings/m0.md: line height and text styles, bold policy) ---------------------------

        /// <summary>
        /// Checks every kit text style against the reference locale's font and the profile's viewports: the weight has a real
        /// face (the TMP weight table, 400 = the font itself) whose font loads; <c>fontSize × scale</c> and
        /// <c>lineHeight × scale</c> are whole device pixels at every viewport scale (<paramref name="scales"/>: UI Toolkit
        /// sets text at whole device pixels and rounds a text element's height up to them, so anything else drifts from
        /// Chromium, most visibly in stacked text). Every font size and line height gets its own line-box twin
        /// (<see cref="FontTwinGenerator.LineBox"/>). Errors name the viewport and the nearest sizes that fit.
        /// </summary>
        internal static List<string> ValidateTextStyles(string path, TMP_FontAsset reference, IReadOnlyList<(UnityEngine.Vector2Int viewport, double scale)> scales)
        {
            var errors = new List<string>();
            var metrics = new Dictionary<TMP_FontAsset, FaceInfo>();
            JObject styles;
            try
            {
                using (var reader = new JsonTextReader(new StringReader(File.ReadAllText(path))) { FloatParseHandling = FloatParseHandling.Double })
                    styles = JObject.Load(reader);
            }
            catch (Exception e) when (e is IOException || e is UnauthorizedAccessException || e is JsonException)
            {
                errors.Add("cannot read the kit's text styles '" + path + "': " + e.Message);
                return errors;
            }

            foreach (var p in styles.Properties())
            {
                var style = p.Value as JObject;
                double? Num(string key)
                {
                    var t = style?[key];
                    return t != null && (t.Type == JTokenType.Integer || t.Type == JTokenType.Float) ? t.Value<double>() : (double?)null;
                }
                var size = Num("fontSize");
                var line = Num("lineHeight");
                var weight = Num("weight") ?? 400;
                var prefix = "text style '" + p.Name + "': ";
                if (size == null || line == null || size <= 0 || line <= 0)
                {
                    errors.Add(prefix + "needs a positive fontSize and lineHeight");
                    continue;
                }
                if (weight < 100 || weight > 900 || weight % 100 != 0)
                {
                    errors.Add(prefix + "weight " + Fmt(weight) + " is not one of 100, 200, … 900");
                    continue;
                }
                var w = (int)weight;
                var face = w == 400 ? reference : RealFace(reference, w);
                if (face == null)
                {
                    errors.Add(prefix + "uses weight " + w + ", but the reference locale's font '" + reference.name + "' has no real face for it: add that face to " +
                               "the TMP font asset's weight table (" + w + "). A synthesized weight renders with different advances in UI Toolkit and Chromium.");
                    continue;
                }
                if (!metrics.TryGetValue(face, out var info))
                {
                    try { info = FontTwinGenerator.TwinFaceInfo(face); }
                    catch (FontSetupException e)
                    {
                        if (!errors.Contains(e.Message)) errors.Add(e.Message);
                        continue;
                    }
                    metrics[face] = info;
                }
                var f = size.Value;
                var l = line.Value;
                foreach (var (viewport, scale) in scales ?? new (UnityEngine.Vector2Int, double)[0])
                {
                    double fs = f * scale, ls = l * scale;
                    bool fWhole = Whole(fs), lWhole = Whole(ls);
                    if (fWhole && lWhole) continue;
                    var step = Step(scales);
                    double F(double v) => Math.Max(step, Math.Round(v / step, MidpointRounding.AwayFromZero) * step);
                    errors.Add(prefix + string.Join(" and ", new[] { fWhole ? null : "fontSize " + Fmt(f) + " px", lWhole ? null : "lineHeight " + Fmt(l) + " px" }.Where(x => x != null)) +
                               " is not whole device pixels at the viewport " + viewport.x + "×" + viewport.y + " (scale " + Fmt(scale) + ": " +
                               string.Join(", ", new[] { fWhole ? null : Fmt(fs), lWhole ? null : Fmt(ls) }.Where(x => x != null)) +
                               " px). Text sizes and line heights must be whole device pixels at every viewport the profile declares (UI Toolkit sets text at " +
                               "whole device pixels and rounds a text's height up to them, so stacked text drifts from the design); use multiples of " + step +
                               " px, for example fontSize " + Fmt(F(f)) + " with lineHeight " + Fmt(F(l)) + ".");
                    break;
                }
            }
            return errors;
        }

        /// <summary>Text under this many device px at the smallest viewport is hard to read, and the renderers differ most there.</summary>
        public const double MinReadableDevicePx = 10;

        /// <summary>
        /// One warning naming every kit text style under <see cref="MinReadableDevicePx"/> device px at the profile's smallest
        /// viewport (by panel scale), grouped by font size; null when there is none or the table cannot be read. Kit sync (and
        /// the exporter's kit build, with the same text) says it once for the kit; designs are not linted for it.
        /// </summary>
        internal static string ReadabilityWarning(string path, IReadOnlyList<(UnityEngine.Vector2Int viewport, double scale)> scales)
        {
            if (scales == null || scales.Count == 0) return null;
            JObject styles;
            try { styles = JObject.Parse(File.ReadAllText(path)); }
            catch (Exception e) when (e is IOException || e is UnauthorizedAccessException || e is JsonException) { return null; }
            var smallest = scales.OrderBy(s => s.scale).First();
            var sizes = new List<(string name, double size)>();
            foreach (var p in styles.Properties())
            {
                var t = (p.Value as JObject)?["fontSize"];
                if (t != null && (t.Type == JTokenType.Integer || t.Type == JTokenType.Float)) sizes.Add((p.Name, t.Value<double>()));
            }
            var small = sizes.Where(s => s.size * smallest.scale < MinReadableDevicePx - 1e-9).ToList();
            if (small.Count == 0) return null;
            var larger = sizes.Where(s => s.size * smallest.scale >= MinReadableDevicePx - 1e-9).OrderBy(s => s.size).ToList();
            var groups = small.Select(s => s.size).Distinct().OrderBy(v => v)
                .Select(f => string.Join(", ", small.Where(s => s.size == f).Select(s => s.name)) + " (" + Fmt(f) + "px: " + Fmt(f * smallest.scale) + " device px)");
            return "text styles under " + Fmt(MinReadableDevicePx) + " device px at " + smallest.viewport.x + "×" + smallest.viewport.y + " (scale " + Fmt(smallest.scale) + "): " +
                   string.Join(", ", groups) + ". Such text is hard to read and the renderers differ most there (the fidelity check holds it to wider measured ink limits); " +
                   "keep it for secondary text and use " + (larger.Count > 0 ? larger[0].name + " (" + Fmt(larger[0].size) + "px) or larger" : "larger styles") +
                   " where the design allows it.";
        }

        static TMP_FontAsset RealFace(TMP_FontAsset font, int weight)
        {
            var table = font.fontWeightTable;
            var i = weight / 100;
            return table != null && i < table.Length ? table[i].regularTypeface : null;
        }

        // ---- faces and files -----------------------------------------------------------------------------------------

        sealed class Face
        {
            public string Family;
            public int Weight;
            public bool Italic;
            public string Source;
            public string Owner;
            public string File;
        }

        /// <summary>
        /// The @font-face list: per locale (reference first) every font TMP searches, as its family at 400 plus the faces
        /// of its weight table. One family, weight and style is one file; two different files are an error.
        /// </summary>
        static List<Face> Faces(FontMap.FontsPlan plan, List<string> errors)
        {
            var faces = new List<Face>();
            void Add(string family, int weight, bool italic, TMP_FontAsset asset, bool fromTable)
            {
                string source;
                try { source = TmpSourceFont.GetSourceFontPath(asset); }
                catch (FontSetupException e)
                {
                    if (!errors.Contains(e.Message)) errors.Add(e.Message);
                    return;
                }
                var existing = faces.FirstOrDefault(x => x.Family == family && x.Weight == weight && x.Italic == italic);
                if (existing == null)
                {
                    faces.Add(new Face { Family = family, Weight = weight, Italic = italic, Source = source, Owner = asset.name });
                    return;
                }
                if (existing.Source == source) return;
                if (fromTable && weight == 400 && !italic)
                    errors.Add("the weight table of '" + existing.Owner + "' names '" + asset.name + "' (" + source + ") for weight 400, but weight 400 is the font itself (" +
                               existing.Source + "); remove that entry or point it at the font itself, so the kit and both engines use one file");
                else
                    errors.Add("font family '" + family + "' weight " + weight + (italic ? " italic" : "") + " would be two files in the kit: '" + existing.Source + "' ('" +
                               existing.Owner + "') and '" + source + "' ('" + asset.name + "'). Give the TMP font assets different family names, or use one source font.");
            }

            foreach (var locale in plan.Locales)
            {
                if (!plan.Chains.TryGetValue(locale, out var chain)) continue;
                foreach (var asset in chain)
                {
                    var family = asset.faceInfo.familyName;
                    if (string.IsNullOrWhiteSpace(family)) continue; // reported by the plan
                    Add(family, 400, false, asset, false);
                    var table = asset.fontWeightTable;
                    if (table == null) continue;
                    for (int i = 1; i < table.Length && i <= 9; i++)
                    {
                        if (table[i].regularTypeface != null) Add(family, i * 100, false, table[i].regularTypeface, true);
                        if (table[i].italicTypeface != null) Add(family, i * 100, true, table[i].italicTypeface, true);
                    }
                }
            }
            return faces;
        }

        /// <summary>
        /// Kit file name → bytes for the faces' source fonts and the licence files next to them: generic ones (OFL.txt,
        /// LICENSE, …) and family ones whose prefix starts a synced font file's name (RobotoMono-LICENSE.txt for
        /// RobotoMono-Regular.ttf); other families' licences in the same folder are not copied. Names stay the source file
        /// names; a licence whose name is taken by a different file gets its folder name as a prefix.
        /// </summary>
        static SortedDictionary<string, byte[]> FontFiles(List<Face> faces, List<string> errors)
        {
            var files = new SortedDictionary<string, byte[]>(StringComparer.Ordinal);
            var origin = new Dictionary<string, string>(StringComparer.Ordinal);
            var folders = new List<string>();
            var stems = new Dictionary<string, List<string>>(StringComparer.Ordinal);
            foreach (var face in faces)
            {
                var name = Path.GetFileName(face.Source);
                face.File = name;
                if (origin.TryGetValue(name, out var other) && other == face.Source) continue;
                var bytes = File.ReadAllBytes(Path.GetFullPath(face.Source));
                if (files.TryGetValue(name, out var taken) && !taken.SequenceEqual(bytes))
                {
                    errors.Add("two different font files are named '" + name + "' ('" + other + "' and '" + face.Source + "'); rename one of them");
                    continue;
                }
                files[name] = bytes;
                origin[name] = face.Source;
                var folder = Path.GetDirectoryName(face.Source)?.Replace('\\', '/');
                if (folder == null) continue;
                if (!folders.Contains(folder)) folders.Add(folder);
                if (!stems.TryGetValue(folder, out var list)) stems[folder] = list = new List<string>();
                list.Add(Path.GetFileNameWithoutExtension(face.Source));
            }
            bool IsLicence(string folder, string name)
            {
                if (name.EndsWith(".meta", StringComparison.OrdinalIgnoreCase)) return false;
                if (LicenceName.IsMatch(name)) return true;
                var m = PrefixedLicence.Match(name);
                return m.Success && stems[folder].Any(stem => stem.StartsWith(m.Groups[1].Value, StringComparison.OrdinalIgnoreCase));
            }
            foreach (var folder in folders)
            {
                var abs = Path.GetFullPath(folder);
                if (!Directory.Exists(abs)) continue;
                foreach (var licence in Directory.GetFiles(abs).Select(Path.GetFileName).Where(n => IsLicence(folder, n)).OrderBy(n => n, StringComparer.Ordinal))
                {
                    var bytes = File.ReadAllBytes(Path.Combine(abs, licence));
                    var name = licence;
                    if (files.TryGetValue(name, out var taken))
                    {
                        if (taken.SequenceEqual(bytes)) continue;
                        name = Path.GetFileName(folder) + "-" + licence;
                        if (files.TryGetValue(name, out taken) && !taken.SequenceEqual(bytes))
                        {
                            errors.Add("two different licence files would be '" + name + "' in the kit; rename one of them");
                            continue;
                        }
                    }
                    files[name] = bytes;
                }
            }
            return files;
        }

        static string FontsCss(List<Face> faces)
        {
            var sb = new StringBuilder();
            sb.Append(Marker).Append('\n');
            foreach (var f in faces)
            {
                sb.Append("@font-face { font-family: \"").Append(CssString(f.Family)).Append("\"; ");
                if (f.Italic) sb.Append("font-style: italic; ");
                sb.Append("font-weight: ").Append(f.Weight.ToString(CultureInfo.InvariantCulture)).Append("; src: url(\"").Append(CssString(f.File)).Append("\")");
                var format = Format(f.File);
                if (format != null) sb.Append(" format(\"").Append(format).Append("\")");
                sb.Append("; }\n");
            }
            return sb.ToString();
        }

        static string Format(string file)
        {
            switch (Path.GetExtension(file).ToLowerInvariant())
            {
                case ".ttf": return "truetype";
                case ".otf": return "opentype";
                case ".ttc": return "collection";
                case ".woff": return "woff";
                case ".woff2": return "woff2";
                default: return null;
            }
        }

        static string CssString(string s) => (s ?? "").Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "").Replace("\r", "");

        /// <summary>fonts.json next to fonts.css: locale → family names in TMP's search order, keys sorted, LF.</summary>
        static string FontsJson(FontMap.FontsPlan plan)
        {
            var o = new JObject();
            foreach (var locale in plan.Locales.OrderBy(l => l, StringComparer.Ordinal))
                if (plan.LocaleFamilies.TryGetValue(locale, out var families))
                    o[locale] = new JArray(families.Cast<object>().ToArray());
            return o.ToString(Formatting.Indented).Replace("\r\n", "\n") + "\n";
        }

        /// <summary>kit.config.json with the profile's values; the original bytes when nothing changes (key order and other keys are kept).</summary>
        static byte[] UpdatedConfig(JObject config, byte[] original, DesignUiProfile profile, FontMap.FontsPlan plan)
        {
            var updated = (JObject)config.DeepClone();
            updated["reference"] = new JArray(profile.referenceResolution.x, profile.referenceResolution.y);
            updated["viewports"] = new JArray(profile.viewports.Select(v => (object)new JArray(v.x, v.y)).ToArray());
            updated["screenMatch"] = double.Parse(profile.screenMatch.ToString("R", CultureInfo.InvariantCulture), CultureInfo.InvariantCulture);
            updated["locales"] = new JArray(plan.Locales.Cast<object>().ToArray());
            if (updated["referenceLocale"] != null) updated["referenceLocale"] = plan.ReferenceLocale;
            return JToken.DeepEquals(config, updated) ? original : Utf8(updated.ToString(Formatting.None) + "\n");
        }

        static string KitRelative(JObject config, string key, string fallback, List<string> errors)
        {
            var token = config[key];
            var value = token == null ? fallback : token.Type == JTokenType.String ? token.Value<string>().Replace('\\', '/') : null;
            if (string.IsNullOrEmpty(value) || Path.IsPathRooted(value) || value.Split('/').Any(s => s == ".." || s.Length == 0))
            {
                errors.Add(ConfigFileName + " has an invalid \"" + key + "\": expected a path inside the kit folder");
                return null;
            }
            return value;
        }

        /// <summary>
        /// Writes when the content differs; generated text is compared with CRLF read as LF and a BOM ignored (a Windows
        /// checkout is not a change). The new content goes to a temp file next to it that then replaces the file, so a reader
        /// never sees half a file.
        /// </summary>
        static bool WriteIfChanged(string path, byte[] bytes, bool text)
        {
            if (File.Exists(path))
            {
                var old = File.ReadAllBytes(path);
                if (text ? Utf8Text(old).Replace("\r\n", "\n") == Utf8Text(bytes) : old.SequenceEqual(bytes)) return false;
            }
            var dir = Path.GetDirectoryName(path);
            if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
            var tmp = path + ".tmp-" + Guid.NewGuid().ToString("N").Substring(0, 8);
            try
            {
                File.WriteAllBytes(tmp, bytes);
                if (File.Exists(path)) File.Replace(tmp, path, null);
                else File.Move(tmp, path);
            }
            finally { if (File.Exists(tmp)) File.Delete(tmp); }
            return true;
        }

        /// <summary>UTF-8 text without its byte order mark.</summary>
        static string Utf8Text(byte[] bytes) => new UTF8Encoding(false).GetString(bytes, Preamble(bytes).Length, bytes.Length - Preamble(bytes).Length);

        /// <summary>The UTF-8 byte order mark at the start of <paramref name="bytes"/>, else nothing.</summary>
        static byte[] Preamble(byte[] bytes) => bytes.Length >= 3 && bytes[0] == 0xEF && bytes[1] == 0xBB && bytes[2] == 0xBF ? new byte[] { 0xEF, 0xBB, 0xBF } : new byte[0];

        static byte[] Utf8(string text) => new UTF8Encoding(false).GetBytes(text.Replace("\r\n", "\n"));

        static string Fmt(double v) => v.ToString("R", CultureInfo.InvariantCulture);

        static bool Whole(double v) => Math.Abs(v - Math.Round(v)) < 1e-6;

        /// <summary>The smallest whole px step that is whole device pixels at every scale (searched up to 64 px).</summary>
        static int Step(IReadOnlyList<(UnityEngine.Vector2Int viewport, double scale)> scales)
        {
            for (int k = 1; k <= 64; k++)
                if (scales.All(s => Whole(k * s.scale))) return k;
            return 64;
        }

        static KitSyncResult Failed(IEnumerable<string> errors, List<string> warnings, List<string> notes, string kitDir = null) =>
            new KitSyncResult { Errors = errors.ToList(), Warnings = warnings, Notes = notes, KitDir = kitDir };

        /// <summary>The Unity project folder (the parent of Assets/).</summary>
        static string ProjectRoot => Path.GetDirectoryName(UnityEngine.Application.dataPath);
    }
