using System.Collections.Generic;
using System.Text;

namespace DesignUi.Editor
{
    /// <summary>
    /// Writes the screen USS: the rules of <see cref="CompiledScreen.Rules"/> in order, one declaration per line, a blank
    /// line between rules, \n line endings. USS has CSS comments only, so the generated marker is a <c>/* */</c> comment.
    /// </summary>
    public static class UssWriter
    {
        public const string Header = "/* auto-generated by com.ertugrulgaziakcan.design-ui */";

        public static string Write(CompiledScreen s) => Write(s, null);

        /// <param name="imports">Style sheets the screen imports (<c>@import url("…")</c> after the marker), relative to the USS file.</param>
        public static string Write(CompiledScreen s, IReadOnlyList<string> imports)
        {
            var sb = new StringBuilder();
            sb.Append(Header).Append('\n');
            foreach (var path in imports ?? new string[0]) sb.Append("@import url(\"").Append(ScreenBuilder.UrlPath(path)).Append("\");\n");
            foreach (var rule in s.Rules)
            {
                sb.Append('\n').Append(rule.Selector).Append(" {\n");
                foreach (var d in rule.Declarations) sb.Append("    ").Append(d.Property).Append(": ").Append(d.Value).Append(";\n");
                sb.Append("}\n");
            }
            return sb.ToString();
        }
    }
}
