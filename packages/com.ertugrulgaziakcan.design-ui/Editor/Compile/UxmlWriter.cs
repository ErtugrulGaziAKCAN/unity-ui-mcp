using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace DesignUi.Editor
{
    /// <summary>
    /// Writes the screen UXML (spec 8): one line per element, every element named, styles only through classes. Lines end
    /// with \n, so a one-element change is a one-line diff. The screen declares its repeats' item templates
    /// (<c>&lt;ui:Template&gt;</c>), which the generated view clones items from; a container root is a
    /// <see cref="DesignUi.DesignScreen"/> (<c>dui:</c>, the package's runtime namespace). A localized text is a
    /// <c>&lt;Bindings&gt;</c> child (<see cref="CompiledElement.Bindings"/>): the String Table and entry of each bound property.
    /// </summary>
    public static class UxmlWriter
    {
        public const string Header = "<!-- auto-generated by com.ertugrulgaziakcan.design-ui -->";
        const string Open = "<ui:UXML xmlns:ui=\"UnityEngine.UIElements\" editor-extension-mode=\"False\">";
        const string OpenWithRuntime = "<ui:UXML xmlns:ui=\"UnityEngine.UIElements\" xmlns:dui=\"" + ScreenBuilder.RuntimeNamespace + "\" editor-extension-mode=\"False\">";
        const string Close = "</ui:UXML>";

        /// <param name="ussFileName">The screen's style sheet, relative to the UXML file.</param>
        public static string Write(CompiledScreen s, string ussFileName)
        {
            var sb = new StringBuilder();
            sb.Append(Header).Append('\n');
            sb.Append(s.Root.Tag == ScreenBuilder.ScreenTag || UsesRuntime(s.Root) ? OpenWithRuntime : Open).Append('\n');
            foreach (var r in s.Repeats)
                if (r.TemplateFile != null)
                    sb.Append("    <ui:Template name=\"").Append(Escape(System.IO.Path.GetFileNameWithoutExtension(r.TemplateFile)))
                      .Append("\" src=\"").Append(Escape(r.TemplateFile)).Append("\" />\n");
            sb.Append("    <Style src=\"").Append(Escape(ussFileName)).Append("\" />\n");
            Element(sb, s.Root, 1);
            sb.Append(Close).Append('\n');
            return sb.ToString();
        }

        /// <summary>
        /// The item template of a repeat (list slots, the inline pool's further items). It has no style sheet: items live
        /// under the screen root, whose sheet styles them (also through the root's state and breakpoint classes).
        /// </summary>
        public static string WriteItemTemplate(CompiledRepeat repeat)
        {
            var sb = new StringBuilder();
            sb.Append(Header).Append('\n').Append(repeat.Items.Any(UsesRuntime) ? OpenWithRuntime : Open).Append('\n');
            foreach (var item in repeat.Items) Element(sb, item, 1);
            sb.Append(Close).Append('\n');
            return sb.ToString();
        }

        /// <summary>Whether the element or a descendant is one of the package's runtime elements (<c>dui:</c>).</summary>
        static bool UsesRuntime(CompiledElement e) => e.DescendantsAndSelf().Any(x => TagOf(x).StartsWith("dui:", System.StringComparison.Ordinal));

        /// <summary>
        /// The element's UXML tag: an exact-width Label or Button is the package's DesignLabel or DesignButton, a Label whose
        /// single line is aligned right or centred its DesignOverflowLabel.
        /// </summary>
        static string TagOf(CompiledElement e)
        {
            if (e.OverflowStart && e.Tag == "ui:Label") return ScreenBuilder.OverflowLabelTag;
            if (!e.FitWidth) return e.Tag;
            if (e.Tag == "ui:Label") return ScreenBuilder.FitLabelTag;
            if (e.Tag == "ui:Button") return ScreenBuilder.FitButtonTag;
            return e.Tag;
        }

        static void Element(StringBuilder sb, CompiledElement e, int depth)
        {
            var indent = new string(' ', depth * 4);
            var tag = TagOf(e);
            sb.Append(indent).Append('<').Append(tag);
            Attribute(sb, "name", e.Name);
            if (e.Classes.Count > 0) Attribute(sb, "class", string.Join(" ", e.Classes));
            if (e.PickingIgnore) Attribute(sb, "picking-mode", "Ignore");
            foreach (var a in e.Attributes) Attribute(sb, a.Key, a.Value);
            if (e.EnableRichText.HasValue) Attribute(sb, "enable-rich-text", e.EnableRichText.Value ? "true" : "false");
            if (e.Text != null) Attribute(sb, "text", e.Text);
            if (e.Children.Count == 0 && e.Bindings.Count == 0)
            {
                sb.Append(" />\n");
                return;
            }
            sb.Append(">\n");
            if (e.Bindings.Count > 0)
            {
                // String Table entries of the element's texts (Unity Localization's LocalizedString binding, through DesignText)
                var inner = indent + "    ";
                sb.Append(inner).Append("<Bindings>\n");
                foreach (var b in e.Bindings)
                {
                    sb.Append(inner).Append("    <").Append(ScreenLocalization.BindingType);
                    Attribute(sb, "property", b.Property);
                    Attribute(sb, "table", b.Table);
                    Attribute(sb, "entry", b.Entry);
                    sb.Append(" />\n");
                }
                sb.Append(inner).Append("</Bindings>\n");
            }
            foreach (var child in e.Children) Element(sb, child, depth + 1);
            sb.Append(indent).Append("</").Append(tag).Append(">\n");
        }

        static void Attribute(StringBuilder sb, string name, string value) => sb.Append(' ').Append(name).Append("=\"").Append(Escape(value)).Append('"');

        static readonly Dictionary<char, string> Entities = new Dictionary<char, string>
        {
            { '&', "&amp;" }, { '<', "&lt;" }, { '>', "&gt;" }, { '"', "&quot;" }, { '\n', "&#10;" }, { '\r', "&#13;" }, { '\t', "&#9;" },
        };

        /// <summary>
        /// Attribute value escaping. Characters XML 1.0 cannot hold at all (C0 controls other than tab, LF and CR,
        /// U+FFFE, U+FFFF and unpaired surrogates) are dropped; they are invisible and no entity can carry them.
        /// </summary>
        static string Escape(string value)
        {
            var sb = new StringBuilder(value.Length);
            for (int i = 0; i < value.Length; i++)
            {
                var c = value[i];
                if (char.IsHighSurrogate(c))
                {
                    if (i + 1 < value.Length && char.IsLowSurrogate(value[i + 1])) { sb.Append(c).Append(value[i + 1]); i++; }
                    continue;
                }
                if (char.IsLowSurrogate(c) || c == '\uFFFE' || c == '\uFFFF' || (c < 0x20 && c != '\t' && c != '\n' && c != '\r')) continue;
                if (Entities.TryGetValue(c, out var entity)) sb.Append(entity);
                else sb.Append(c);
            }
            return sb.ToString();
        }
    }
}
