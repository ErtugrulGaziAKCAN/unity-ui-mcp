/**
 * `design-export kit claude <kitDir> <outDir>`: the kit as a Claude Design System artifact folder, `<outDir>/project/`:
 *
 * - `README.md`: the design contract for Claude Design (renderRules "claude"): artboard rules, the kit stylesheet,
 *   markup attributes, text styles, fonts, tokens, allowed CSS, every lint rule with its fix, the component cards.
 * - `tokens.json` in the Design System's list shape: colours in one theme, type (font files, the family, the kit text
 *   styles as groups), spacing, radius and shadow, all with the kit's names, so `var(--name)` means the same everywhere.
 * - `fonts/<file>` (the font files kit sync copied from the Unity project) and their licences under `licenses/`.
 * - `components/<Name>/README.md` (guidelines) and `preview.html` (line 1 `<!-- @dsCard … -->`, then the component's
 *   lint-clean screen with the kit tokens inlined) for each kit component, and a bare `components/Cover/preview.html`.
 * - `design-system.json`: the index of a new system (`createdOnFiles`), written last. When the system already exists,
 *   the publisher keeps the live index's keys and changes only `lastChange` and the title.
 */
export interface ClaudeDsOptions { title?: string; by?: string; now?: Date; force?: boolean }
export interface ClaudeDsResult { projectDir: string; files: string[] }

/** Token and type style names the Design System page reads. */
export const CLAUDE_TOKEN_NAME = /^[A-Za-z0-9][A-Za-z0-9_.-]{0,63}$/;
const THEME = { id: "dark", name: "Dark" };
const VIA = "design-export kit claude";

/** The stylesheet an artboard pastes first: the kit tokens as one :root block, then the base stylesheet. */
export const kitStylesheet = (kit: KitConfig): string => kitStylesheetFrom(readKitTokens(kit), readTextStyles(kit));

/** PascalCase ASCII identifier from a title (the index's namespace). */
export function namespaceOf(title: string): string {
  const id = title.split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1).toLowerCase()).join("");
  return /^[A-Za-z]/.test(id) ? id : `Ds${id}`;
}

const familyKey = (tokenName: string) => tokenName.replace(/^font-/, "").toLowerCase();

/** The kit tokens and text styles in the Design System's tokens.json shape. */
export function buildTokensJson(title: string, tokens: readonly KitToken[], styles: readonly TextStyle[], fonts: readonly KitFontFile[]): Record<string, unknown> {
  const list = (fam: KitToken["family"]) => tokens.filter((t) => t.family === fam).map((t) => ({ name: t.name, value: t.value, usage: t.usage }));
  const font = tokens.find((t) => t.family === "font");
  const families: Record<string, string> = Object.fromEntries(tokens.filter((t) => t.family === "font").map((t) => [familyKey(t.name), t.value]));
  return {
    name: title,
    version: 1,
    meta: { source: "Generated by design-export kit claude from the design kit; change the kit and export again." },
    color: { themes: [THEME], tokens: tokens.filter((t) => t.family === "color").map((t) => ({ name: t.name, value: { [THEME.id]: t.value }, usage: t.usage })) },
    type: {
      fonts: fonts.map((f) => ({ family: f.family, file: `fonts/${path.posix.basename(f.file)}`, weight: f.weight, style: f.style })),
      families,
      // one group in text-styles.json order: every number comes from that file
      groups: [{
        name: "Kit text styles",
        family: font ? familyKey(font.name) : Object.keys(families)[0] ?? "ui",
        styles: styles.map((s) => ({
          name: s.name, fontSize: `${s.fontSize}px`, lineHeight: `${s.lineHeight}px`, fontWeight: s.weight, usage: `Class .text-${s.name}.`,
        })),
      }],
    },
    spacing: { tokens: list("spacing") },
    radius: { tokens: list("radius") },
    shadow: { tokens: list("shadow") },
  };
}

// ---- tokens.json validation (what the Design System page reads; anything else it drops) -----------------------------

const HEX = /^#([0-9a-f]{3}|[0-9a-f]{4}|[0-9a-f]{6}|[0-9a-f]{8})$/i;
const COLOR_FN = /^(rgb|rgba|hsl|hsla|oklch|oklab|lab|lch|color)\([^()]*\)$/i;
const LENGTH = /^(-?\d+(\.\d+)?(px|rem|em|%)?|0)$/;
const SHADOW_COLOR_FN = /\b(rgb|rgba|hsl|hsla|oklch|oklab|lab|lch|color)\([^()]*\)/gi;

function colorProblem(v: unknown, colorNames: Set<string>): string | null {
  if (typeof v !== "string") return "not a string";
  const s = v.trim();
  if (/var\(/i.test(s)) return `${s}: var() is dropped`;
  const alias = /^\{([^}]+)\}$/.exec(s);
  if (alias) return colorNames.has(alias[1]) ? null : `${s}: alias of a missing colour token`;
  if (HEX.test(s) || COLOR_FN.test(s)) return null;
  return `${s}: not hex or a colour function with plain numbers (named colours are dropped)`;
}

/** Problems that would make the Design System page drop a token, a style or a whole family; [] when the file reads cleanly. */
export function validateTokensJson(t: unknown): string[] {
  const errs: string[] = [];
  if (!t || typeof t !== "object") return ["tokens.json is not an object"];
  const o = t as Record<string, unknown>;
  const seen = new Map<string, string>();
  const name = (fam: string, n: unknown) => {
    if (typeof n !== "string" || !CLAUDE_TOKEN_NAME.test(n)) { errs.push(`${fam}: token name "${String(n)}" is not ${CLAUDE_TOKEN_NAME}`); return; }
    if (seen.has(n)) errs.push(`${fam}: token name ${n} is used more than once (also in ${seen.get(n)})`);
    else seen.set(n, fam);
  };
  const tokensOf = (fam: string): Record<string, unknown>[] | null => {
    const f = o[fam] as { tokens?: unknown } | undefined;
    if (f === undefined) return null;
    if (!f || typeof f !== "object" || !Array.isArray(f.tokens)) { errs.push(`${fam}: must be { "tokens": [ { "name", "value", "usage" } ] } (a name-to-value map is not read)`); return null; }
    return f.tokens as Record<string, unknown>[];
  };

  // colours: one flat list with themes
  const color = o.color as { themes?: { id?: unknown }[] } | undefined;
  const themes = Array.isArray(color?.themes) ? color!.themes!.map((x) => String(x?.id ?? "")) : [];
  if (color && !themes.length) errs.push("color: needs at least one theme");
  for (const id of themes) if (!CLAUDE_TOKEN_NAME.test(id)) errs.push(`color: theme id "${id}" is not ${CLAUDE_TOKEN_NAME}`);
  const colors = tokensOf("color") ?? [];
  const colorNames = new Set(colors.map((c) => String(c.name)));
  for (const c of colors) {
    name("color", c.name);
    const values = typeof c.value === "object" && c.value !== null ? Object.entries(c.value as Record<string, unknown>) : [[themes[0] ?? "", c.value] as [string, unknown]];
    for (const [theme, v] of values) {
      if (theme && themes.length && !themes.includes(theme)) errs.push(`color token ${String(c.name)}: theme ${theme} is not declared`);
      const p = colorProblem(v, colorNames);
      if (p) errs.push(`color token ${String(c.name)}: ${p}`);
    }
  }
  for (const fam of ["spacing", "radius"]) {
    for (const x of tokensOf(fam) ?? []) {
      name(fam, x.name);
      if (typeof x.value !== "string" && typeof x.value !== "number") errs.push(`${fam} token ${String(x.name)}: value must be a length`);
      else if (typeof x.value === "string" && !LENGTH.test(x.value.trim())) errs.push(`${fam} token ${String(x.name)}: ${x.value} is not px, rem, em, % or a number`);
    }
  }
  for (const x of tokensOf("shadow") ?? []) {
    name("shadow", x.name);
    const v = typeof x.value === "string" ? x.value : "";
    if (!v || v.length > 400) errs.push(`shadow token ${String(x.name)}: needs a box-shadow string of at most 400 characters`);
    if (/var\(|url\(/i.test(v)) errs.push(`shadow token ${String(x.name)}: var() and url() are dropped`);
    const words = v.replace(SHADOW_COLOR_FN, "").split(/[\s,]+/).filter(Boolean);
    for (const w of words) if (!(LENGTH.test(w) || HEX.test(w) || /^(inset|none)$/i.test(w))) errs.push(`shadow token ${String(x.name)}: "${w}" is not a length, a hex or function colour, inset or none`);
  }

  // type
  const type = o.type as { fonts?: unknown; families?: unknown; groups?: unknown } | undefined;
  if (type) {
    const families = (type.families && typeof type.families === "object" ? type.families : {}) as Record<string, unknown>;
    for (const [k, v] of Object.entries(families)) {
      if (!CLAUDE_TOKEN_NAME.test(k) || k !== k.toLowerCase()) errs.push(`type.families: key "${k}" must be lowercase and match ${CLAUDE_TOKEN_NAME}`);
      if (typeof v !== "string" || v.length > 200 || /[;{}<>\\()]/.test(v) || (v.match(/"/g) ?? []).length % 2 || (v.match(/'/g) ?? []).length % 2) {
        errs.push(`type.families.${k}: must be a font-family stack of at most 200 characters without ; { } < > \\ ( ) and with balanced quotes`);
      }
    }
    for (const f of Array.isArray(type.fonts) ? (type.fonts as Record<string, unknown>[]) : []) {
      if (typeof f.family !== "string" || /["']/.test(f.family)) errs.push(`type.fonts: family ${String(f.family)} must be a bare name`);
      if (typeof f.file !== "string" || !f.file) errs.push(`type.fonts: ${String(f.family)} needs a file`);
    }
    const styleNames = new Set<string>();
    for (const g of Array.isArray(type.groups) ? (type.groups as { family?: unknown; styles?: unknown }[]) : []) {
      if (typeof g.family === "string" && !(g.family in families)) errs.push(`type.groups: family ${g.family} is not a key of type.families`);
      for (const s of Array.isArray(g.styles) ? (g.styles as Record<string, unknown>[]) : []) {
        const n = String(s.name);
        if (!CLAUDE_TOKEN_NAME.test(n)) errs.push(`type style "${n}" is not ${CLAUDE_TOKEN_NAME}`);
        if (styleNames.has(n)) errs.push(`type style ${n} is used more than once`);
        styleNames.add(n);
        if (typeof s.fontSize !== "string" || !LENGTH.test(s.fontSize)) errs.push(`type style ${n}: fontSize ${String(s.fontSize)} is not a length`);
        const lh = s.lineHeight;
        if (lh !== undefined && !(typeof lh === "string" && LENGTH.test(lh)) && !(typeof lh === "number" && lh < 10)) errs.push(`type style ${n}: lineHeight ${String(lh)} is not a length or a unitless number below 10`);
        const fw = s.fontWeight;
        if (fw !== undefined && !(typeof fw === "number" && fw >= 1 && fw <= 1000)) errs.push(`type style ${n}: fontWeight ${String(fw)} is not 1–1000`);
      }
    }
  } else errs.push("type: missing");
  return errs;
}

// ---- cover and previews -------------------------------------------------------------------------------------------

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** The cover (cover.md of the Design System type): colour blocks, one pattern, the name. Classes bind every fill and radius to a token. */
export function coverHtml(title: string, tokens: readonly KitToken[]): string {
  const colors = tokens.filter((t) => t.family === "color").map((t) => t.name);
  const pick = (want: string, i: number) => (colors.includes(want) ? want : colors[i % Math.max(colors.length, 1)] ?? want);
  const c = {
    ground: pick("color-surface-900", 0), slab: pick("color-surface-700", 1), brand: pick("color-accent", 2), signal: pick("color-positive", 3),
    warm: pick("color-warning", 4), ink: pick("color-text-primary", 5), muted: pick("color-text-secondary", 6),
  };
  const dots: string[] = [];
  for (let y = 16; y < 288; y += 32) for (let x = 16; x < 160; x += 32) dots.push(`<circle class="dot" cx="${x}" cy="${y}" r="3"/>`);
  return [
    "<!-- @dsCard height=288 -->",
    "<!doctype html>",
    '<html><head><meta charset="utf-8"><style>',
    "html, body { margin: 0; }",
    `body { background-color: var(--${c.ground}); }`,
    `.cover { position: relative; width: 960px; height: 288px; overflow: hidden; background-color: var(--${c.ground}); font-family: var(--font-ui); }`,
    ".art { position: absolute; left: 480px; top: 0; }",
    `.slab { fill: var(--${c.slab}); }`,
    `.brand { fill: var(--${c.brand}); rx: var(--radius-lg); }`,
    `.signal { fill: var(--${c.signal}); rx: var(--radius-md); }`,
    `.warm { fill: var(--${c.warm}); rx: var(--radius-sm); }`,
    `.dot { fill: var(--${c.brand}); }`,
    `.name { position: absolute; left: 48px; bottom: 84px; max-width: 440px; margin: 0; font-size: 88px; line-height: 0.95; font-weight: 700; color: var(--${c.ink}); }`,
    `.tagline { position: absolute; left: 48px; bottom: 40px; max-width: 440px; margin: 0; font-size: 14px; line-height: 20px; color: var(--${c.muted}); }`,
    "</style></head><body><div class=\"cover\">",
    '<svg class="art" width="480" height="288" viewBox="0 0 480 288">',
    "<!--",
    `  blocks: ${c.slab} 160x288 slab, ${c.brand} 256x192 (radius-lg), ${c.signal} 96x96 (radius-md), ${c.warm} 64x64 (radius-sm)`,
    "  arrangement: one tall slab with satellites, the brand block bleeding off the top and right edge",
    "  pattern: a dot grid, because the kit is precise and technical (every size a whole pixel, spacing on a 4px grid)",
    "  steps and radii: dots at space-8 pitch, gaps of space-4 and space-8; radius-sm, radius-md, radius-lg",
    "-->",
    '<rect class="slab" x="0" y="0" width="160" height="288"/>',
    ...dots,
    '<rect class="brand" x="192" y="-32" width="320" height="192"/>',
    '<rect class="signal" x="192" y="176" width="96" height="96"/>',
    '<rect class="warm" x="304" y="208" width="64" height="64"/>',
    "</svg>",
    `<p class="name">${esc(title)}</p>`,
    '<p class="tagline">Screens that compile to Unity UI Toolkit, one to one.</p>',
    "</div></body></html>",
    "",
  ].join("\n");
}

/** A component card's preview: the marker line, then the component's screen with the kit tokens inlined at the top of its style. */
/** A value for the @dsCard marker: no quote that ends the attribute, no `--` that ends the comment. */
const markerValue = (s: string) => s.replace(/"/g, "'").replace(/-{2,}/g, "–").replace(/[<>]/g, "");

export function previewHtml(c: KitComponent, screenHtml: string, tokens: readonly KitToken[]): string {
  const marker = `<!-- @dsCard group="${markerValue(c.group)}" width=2560 height=1440 subtitle="${markerValue(c.summary)}" -->`;
  const i = screenHtml.indexOf("<style>");
  const body = i < 0 ? screenHtml : screenHtml.slice(0, i + 7) + "\n" + tokensCssBlock(tokens) + screenHtml.slice(i + 7);
  return `${marker}\n${body}`;
}

// ---- writer -------------------------------------------------------------------------------------------------------

export function writeClaudeDesignSystem(kitDir: string, outDir: string, opts: ClaudeDsOptions = {}): ClaudeDsResult {
  const kit = readKit(kitDir);
  const title = opts.title ?? DEFAULT_TITLE;
  const at = (opts.now ?? new Date()).toISOString();
  const faces = readKitFontFiles(kit);
  if (!faces || faces.length === 0) throw new Error(`the kit at ${kit.dir} has no synced fonts (${kit.fontsCss}): run kit sync in the Unity project first, so the design system carries the font files Unity renders with`);
  const tokens = readKitTokens(kit);
  const styles = readTextStyles(kit);
  assertWholeDevicePixels(styles, kit);
  const components = readKitComponents(kit.dir);

  // everything is read and rendered before anything is written
  const files: [string, string | Buffer][] = [];
  files.push(["README.md", renderRules(kit, "claude", { title })]);
  const tokensJson = buildTokensJson(title, tokens, styles, faces);
  const problems = validateTokensJson(tokensJson);
  if (problems.length) throw new Error(`tokens.json would lose entries in the Design System: ${problems.join("; ")}`);
  files.push(["tokens.json", JSON.stringify(tokensJson, null, 2) + "\n"]);
  const fontDir = path.join(kit.dir, path.dirname(kit.fontsCss));
  const byName = new Map<string, string>();
  for (const f of Array.from(new Set(faces.map((x) => x.file)))) {
    const other = byName.get(path.basename(f));
    if (other) throw new Error(`font files ${other} and ${f} share the name ${path.basename(f)}; the design system keeps fonts in one folder`);
    byName.set(path.basename(f), f);
    const src = path.join(kit.dir, f);
    if (!fs.existsSync(src)) throw new Error(`font file ${f} named in ${kit.fontsCss} is missing`);
    files.push([`fonts/${path.basename(f)}`, fs.readFileSync(src)]);
  }
  for (const l of fs.readdirSync(fontDir).filter((n) => LICENCE_FILE.test(n)).sort()) files.push([`licenses/${l}`, fs.readFileSync(path.join(fontDir, l))]);
  for (const c of components) {
    files.push([`components/${c.name}/README.md`, c.guide]);
    files.push([`components/${c.name}/preview.html`, previewHtml(c, fs.readFileSync(path.join(kit.dir, "components", c.file), "utf8"), tokens)]);
  }
  files.push(["components/Cover/preview.html", coverHtml(title, tokens)]);
  const index = {
    v: 3, layout: "files", createdOnFiles: { v: 1, at }, title, namespace: namespaceOf(title), libraries: [], sections: {}, groups: [],
    assetGroups: {}, blobs: {}, docs: { sections: [] },
    lastChange: { by: opts.by ?? "design-export", at, via: VIA, note: "Generated from the design kit: README, tokens, fonts, component previews and cover." },
  };

  const projectDir = path.join(path.resolve(outDir), "project");
  if (fs.existsSync(projectDir) && fs.readdirSync(projectDir).length) {
    if (!opts.force) throw new Error(`${projectDir} already exists; pass --force to replace it`);
    // --force replaces only what this command wrote: a design-system.json whose last change came from it
    let existing: unknown = null;
    try { existing = JSON.parse(fs.readFileSync(path.join(projectDir, "design-system.json"), "utf8")); } catch { /* not ours */ }
    if ((existing as { lastChange?: { via?: string } } | null)?.lastChange?.via !== VIA)
      throw new Error(`${projectDir} was not written by ${VIA} (no design-system.json of it); remove or move it yourself`);
    fs.rmSync(projectDir, { recursive: true, force: true });
  }
  const written: string[] = [];
  const write = (rel: string, data: string | Buffer) => {
    const p = path.join(projectDir, rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, data);
    written.push(rel);
  };
  for (const [rel, data] of files) write(rel, data);
  write("design-system.json", JSON.stringify(index, null, 2) + "\n"); // the index goes last
  return { projectDir, files: written };
}
